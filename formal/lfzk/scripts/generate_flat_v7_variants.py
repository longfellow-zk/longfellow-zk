#!/usr/bin/env python3
"""Generate the hash2–4 flat FS proof modules from the checked hash1 spine.

Each output is ordinary Lean source and is checked independently by Lake.
Run with --check to detect drift without modifying files.
"""

from __future__ import annotations

import argparse
import difflib
from pathlib import Path


MODULES = Path(__file__).resolve().parents[1] / "Lfzk"
KINDS = ("TwoField", "Deployed", "Headline")
HEADER = """/-
Generated by `lfzk/scripts/generate_flat_v7_variants.py` from the hash1 proof.
Edit the hash1 source or the generator, then regenerate and build `Lfzk.FlatV7All`.
-/

"""


def render(kind: str, index: int) -> str:
    text = (MODULES / f"FlatV7{kind}.lean").read_text()
    if kind == "TwoField":
        start = text.index("/-- For hash1, the response-rigidity")
        stop = text.index("/-- The hash1 flat 125-bit terminal envelope", start)
        text = text[:start] + text[stop:]
        text = text.replace("FlatV7TwoField", f"FlatV7Hash{index}TwoField")
    elif kind == "Deployed":
        text = text.replace("FlatV7TwoField", f"FlatV7Hash{index}TwoField")
        text = text.replace("FlatV7Deployed", f"FlatV7Hash{index}Deployed")
    else:
        text = text.replace("FlatV7Deployed", f"FlatV7Hash{index}Deployed")
        text = text.replace("FlatV7Headline", f"FlatV7Hash{index}Headline")

    row = f"v7Hash{index}"
    logv = 5 if index == 4 else 4
    text = text.replace("v7Hash1", row).replace("hash1", f"hash{index}")
    text = text.replace(" 3 C F₁", f" {logv} C F₁")
    text = text.replace(f"zkFieldDensity {row} 3", f"zkFieldDensity {row} {logv}")
    text = text.replace(f"zkCoreAt {row} 3", f"zkCoreAt {row} {logv}")
    text = text.replace(f"{row}.zkCoefficient 3", f"{row}.zkCoefficient {logv}")
    if kind == "Headline":
        text = text.replace("⟨0, by decide⟩", f"⟨{index - 1}, by decide⟩")
        text = text.replace("(0 : Fin 4)", f"({index - 1} : Fin 4)")
    return HEADER + text


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if a generated file differs")
    args = parser.parse_args()
    stale = False
    for index in (2, 3, 4):
        for kind in KINDS:
            path = MODULES / f"FlatV7Hash{index}{kind}.lean"
            expected = render(kind, index)
            if args.check:
                actual = path.read_text() if path.exists() else ""
                if actual != expected:
                    stale = True
                    print("".join(difflib.unified_diff(
                        actual.splitlines(keepends=True), expected.splitlines(keepends=True),
                        fromfile=str(path), tofile="generated", n=2,
                    )))
            else:
                path.write_text(expected)
                print(path)
    return 1 if stale else 0


if __name__ == "__main__":
    raise SystemExit(main())
