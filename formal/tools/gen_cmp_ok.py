#!/usr/bin/env python3
"""Emit `E2Cmp.lean`: `hrlt` and `hslt`, the two range comparisons.

Usage: gen_cmp_ok.py OUTDIR

The chain, once `gen_lt_meaning.py` reports the comparator's `lt` component as
`1 - interpDag <assertion node>`:

    assertion                 interpDag 14406 = 0
    certificate               foldStL <tree> = (eq, 1 - interpDag 14406)
    bit lemmas                each leaf wire is `digitBit 2` of its digit
    digitBit_eq_enc           ... which is `BitLt.enc` of a `Bool`
    BitLt.lt_of_foldStL       bval (rx bits) < bval (order bits)
    natR_bval                 ... which is `natR ((us.map bitrev3).map val3) < order`

The list the certificate folds over is a `tree_fold2`-shaped tree of `++`, and the list
`lt_of_foldStL` wants is `(a.zip b).map (base (enc ·) (enc ·))`. Both are literals, so `++`,
`zip` and `map` all compute and the two are definitionally equal -- `exact` crosses the gap with
no rewriting, which is why the tree never has to be written out here.
"""
import sys

ORDER = 0xFFFFFFFF00000000FFFFFFFFFFFFFFFFBCE6FAADA7179E84F3B9CAC2FC632551
CHUNK0 = 198
ERS0 = 6


def main():
    outdir = sys.argv[1]
    imports = "\n".join(
        ["import quadcert.Gen.E2.E2LtRx", "import quadcert.Gen.E2.E2LtNms", "import quadcert.Gen.E2.E2Recon"]
        + [f"import quadcert.Gen.E2.E2BitB{k:02d}" for k in range(16)]
        + ["import ECDSA.CmpBridge"])

    order_bits = ", ".join("true" if (ORDER >> k) & 1 else "false" for k in range(256))
    rx_bits = ", ".join(f"ECDSA2.digitBitB 2 (inputs {ERS0 + k})" for k in range(256))
    nms_bits = ", ".join(f"ECDSA2.digitBitB 4 (inputs {ERS0 + k})" for k in range(256))
    digits = ", ".join(f"hd{k}" for k in range(256))
    bits = "\n".join(
        f"  obtain ⟨e{k}, r{k}, s{k}⟩ := bits_{k} inputs hone hd{k}" for k in range(256))
    rrw = ", ".join(f"r{k}" for k in range(256))
    srw = ", ".join(f"s{k}" for k in range(256))
    c0 = ", ".join(f"c0_{j}" for j in range(CHUNK0))
    # `clear` takes names separated by spaces, not commas
    c0sp = " ".join(f"c0_{j}" for j in range(CHUNK0))

    src = f'''-- Generated by `formal/tools/gen_cmp_ok.py`. Do not edit.
{imports}

set_option maxRecDepth 4000000
set_option maxHeartbeats 4000000

/-!
# `hrlt` and `hslt`: the two range comparisons

`soundness_of_v2`'s last two circuit hypotheses. The comparator certificates report the fold's
`lt` component as `1 - interpDag <assertion node>`, so the assertion makes it `1`; the bit
lemmas turn the leaf wires into `BitLt.enc` of `Bool`s; and `BitLt.lt_of_foldStL` plus
`ECDSA2.natR_bval` land on the specification's `natR … < order`.
-/

namespace Ecdsa2.Assembly

open Quadcert Quadcert.Gen.Ecdsa2 Ecdsa2.Meaning ECDSA2

variable {{F : Type}} [Field F] [CharP F p256]

/-- The group order's bits, least significant first -- the constants the comparator's `base`
    nodes carry. -/
def orderBits : List Bool := [{order_bits}]

theorem bval_orderBits : ECDSA2.BitLt.bval orderBits = {ORDER} := by decide

/-- `rx`'s bits, in `ers` order, as `Bool`s. -/
noncomputable def rxBits (inputs : Nat → F) : List Bool := [{rx_bits}]

/-- The same for the negated-`s` value the circuit calls `nms`. -/
noncomputable def nmsBits (inputs : Nat → F) : List Bool := [{nms_bits}]

theorem cmp_ok (inputs : Nat → F) (hone : inputs 0 = 1)
    (hacc : Accepts (Ecdsa2.circuit F) inputs) :
    natR (((usList inputs).map ECDSA2.bitrev3).map val3) < {ORDER} ∧
      natS (((usList inputs).map ECDSA2.bitrev3).map val3) < {ORDER} := by
  obtain ⟨{digits}⟩ := digits_tuple inputs hone hacc
  have H := Ecdsa2.assertions_zero inputs hacc
  simp only [RawCircuit.toRecs, List.forall_mem_map,
    show (raw.asserts) = asserts_0 ++ asserts_1 ++ asserts_2 ++ asserts_3 ++ asserts_4 from rfl,
    List.forall_mem_append] at H
  obtain ⟨⟨⟨⟨H0, H1⟩, H2⟩, H3⟩, H4⟩ := H
  simp only [asserts_0, List.forall_mem_cons, List.forall_mem_nil] at H0
  obtain ⟨{c0}, -⟩ := H0
  have hrx := lt_rx_order (F := F) inputs hone
  have hnms := lt_nms_order (F := F) inputs hone
{bits}
  -- The leaf wires become `enc` of a `Bool`; `digitBit_eq_enc` needs no `IsDigit`, since
  -- `digitBit` is already a decidable test on `val3 (bitrev3 u)`.
  simp only [{rrw}, ECDSA2.digitBit_eq_enc] at hrx
  simp only [{srw}, ECDSA2.digitBit_eq_enc] at hnms
  have hr2 := congrArg Prod.snd hrx
  have hs2 := congrArg Prod.snd hnms
  -- the certificate renders the complement as `1 + (-1) * w`, not `1 - w`
  rw [c0_1] at hr2
  rw [c0_0] at hs2
  simp only [mul_zero, add_zero] at hr2 hs2
  clear {c0sp} H1 H2 H3 H4 hrx hnms
  have hrb : ECDSA2.BitLt.bval (rxBits inputs) < ECDSA2.BitLt.bval orderBits :=
    ECDSA2.BitLt.lt_of_foldStL (rxBits inputs) orderBits rfl hr2
  have hsb : ECDSA2.BitLt.bval (nmsBits inputs) < ECDSA2.BitLt.bval orderBits :=
    ECDSA2.BitLt.lt_of_foldStL (nmsBits inputs) orderBits rfl hs2
  rw [bval_orderBits] at hrb hsb
  refine ⟨?_, ?_⟩
  · rw [ECDSA2.natR_bval, ← usList_reverse inputs, List.reverse_reverse]
    simpa only [rxBits, List.map_cons, List.map_nil] using hrb
  · rw [ECDSA2.natS_bval, ← usList_reverse inputs, List.reverse_reverse]
    simpa only [nmsBits, List.map_cons, List.map_nil] using hsb

end Ecdsa2.Assembly
'''
    open(outdir + "/E2Cmp.lean", "w").write(src)
    print(f"wrote {outdir}/E2Cmp.lean")


main()
