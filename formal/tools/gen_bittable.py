#!/usr/bin/env python3
"""Emit `ECDSA/BitTable.lean`: `digitBit` and its 24 evaluations at the encoded nodes.

Usage: gen_bittable.py > formal/circuits/ECDSA/BitTable.lean

Mechanical, but 24 lemmas each needing two if-chains decided (`bitrev3` over the eight nodes and
`val3` over the eight indices) is exactly the kind of thing to generate rather than type.

It lives outside `EcdsaV2` on purpose: `EcdsaV2` is imported by all 112 generated round and mux
modules, so extending it costs a full rebuild of them.
"""
NODES = [-8, -6, -4, -2, 0, 2, 4, 6]
REV = [0, 4, 2, 6, 1, 5, 3, 7]   # bitrev3: the circuit's `4e+2r+s` read as `e+2r+4s`
SEL = {"E": 1, "R": 2, "S": 4}

PAIRS = [(k, j) for k in range(8) for j in range(k)]
DIFF = {2: "d2", 4: "d4", 6: "d6", 8: "d8", 10: "d10", 12: "d12", 14: "d14"}
SMALL = {1: "one_ne_zero", 2: "d2", 3: "n3", 4: "d4", 5: "n5", 6: "d6", 7: "n7"}


def proj(i, n=8):
    """Component `i` of a right-nested `n`-fold conjunction."""
    return ".".join(["2"] * i + ["1"]) if i < n - 1 else ".".join(["2"] * (n - 1))


def bundle(name, vals, witness):
    stmt = " ∧\n    ".join(f"(({vals[k]} : F) ≠ ({vals[j]} : F))" for k, j in PAIRS)
    args = ", ".join(
        "bnum_ne' " + witness(vals[k] - vals[j]) + " (by norm_num)" for k, j in PAIRS)
    return (f"private lemma {name} :\n    {stmt} := by\n"
            f"  obtain ⟨d2, d4, d6, d8, d10, d12, d14⟩ := bdiff_ne (F := F)\n"
            f"  have n3 : (3 : F) ≠ 0 := NeZero.ne _\n"
            f"  have n5 : (5 : F) ≠ 0 := NeZero.ne _\n"
            f"  have n7 : (7 : F) ≠ 0 := NeZero.ne _\n"
            f"  exact ⟨{args}⟩\n")


print('''import ECDSA.EcdsaV2

/-!
# The digit's three bits, at the eight encoded nodes

`circuit.rs` packs a digit as `4e + 2r + s` and stores the node `2d - 8`; three separate bit
tables hold `e`, `r` and `s`, and those are what `e_eq`, `rx_eq` and `nmsinv` sum. On the
specification side the same three bits are `muxE`, `muxR`, `muxS` of `val3 (bitrev3 u)` --
`bitrev3` because `muxPoint` packs the bits the other way round.

`digitBit` names that per-digit contribution; the lemmas below evaluate it at each node, so a
generated bit lemma is a cone chain plus an eight-way case split and nothing else.

This is a separate module rather than an extension of `EcdsaV2` because `EcdsaV2` is imported by
all 112 generated round and mux modules: extending it would rebuild every one of them.

Generated by `formal/tools/gen_bittable.py`.
-/

namespace ECDSA2

variable {F : Type} [Field F] [NeZero (2 : F)] [NeZero (3 : F)] [NeZero (4 : F)]
  [NeZero (5 : F)] [NeZero (6 : F)] [NeZero (7 : F)]

/-- `reconstructE` / `reconstructR` / `reconstructS`'s per-digit contribution, as a function of
    the *encoded* node the circuit stores. `sel = 1, 2, 4` selects `muxE`, `muxR`, `muxS`. -/
noncomputable def digitBit (sel : Nat) (u : F) : F :=
  if (val3 (bitrev3 u) / sel) % 2 = 1 then 1 else 0

private lemma bnum_ne' {a b c : F} (hc : c ≠ 0) (h : a - b = c) : a ≠ b := by
  intro he; exact hc (by rw [← h, he, sub_self])

private lemma bdiff_ne :
    ((2 : F) ≠ 0) ∧ ((4 : F) ≠ 0) ∧ ((6 : F) ≠ 0) ∧ ((8 : F) ≠ 0) ∧ ((10 : F) ≠ 0) ∧
      ((12 : F) ≠ 0) ∧ ((14 : F) ≠ 0) := by
  have n2 : (2 : F) ≠ 0 := NeZero.ne _
  have n4 : (4 : F) ≠ 0 := NeZero.ne _
  have n5 : (5 : F) ≠ 0 := NeZero.ne _
  have n6 : (6 : F) ≠ 0 := NeZero.ne _
  have n7 : (7 : F) ≠ 0 := NeZero.ne _
  refine ⟨n2, n4, n6, ?_, ?_, ?_, ?_⟩
  · rw [show (8 : F) = 2 * 4 by norm_num]; exact mul_ne_zero n2 n4
  · rw [show (10 : F) = 2 * 5 by norm_num]; exact mul_ne_zero n2 n5
  · rw [show (12 : F) = 2 * 6 by norm_num]; exact mul_ne_zero n2 n6
  · rw [show (14 : F) = 2 * 7 by norm_num]; exact mul_ne_zero n2 n7
''')

print(bundle("bnodes_ne", NODES, lambda d: DIFF[d]))
print(bundle("bidx_ne", list(range(8)), lambda d: SMALL[d]))

an = [f"a{k}_{j}" for k, j in PAIRS]
bn = [f"b{k}_{j}" for k, j in PAIRS]

SEP = " ∧\n    "
HOLES = ", ".join("?_" for _ in range(8))

rev_stmt = SEP.join(f"(bitrev3 ({NODES[k]} : F) = {REV[k]})" for k in range(8))
print(f"""private lemma bbitrev :
    {rev_stmt} := by
  obtain ⟨{', '.join(an)}⟩ := bnodes_ne (F := F)
  refine ⟨{HOLES}⟩ <;>
    simp only [bitrev3, {', '.join(an)}, eq_self_iff_true, if_true, if_false,
      ite_false, ite_true, reduceIte]
""")

val_stmt = SEP.join(f"(val3 ({k} : F) = {k})" for k in range(8))
print(f"""private lemma bval3 :
    {val_stmt} := by
  obtain ⟨{', '.join(bn)}⟩ := bidx_ne (F := F)
  refine ⟨{HOLES}⟩ <;>
    simp only [val3, {', '.join(bn)}, eq_self_iff_true, if_true, if_false,
      ite_false, ite_true, reduceIte]
""")

print("""/-! The 24 evaluations: `sel ∈ {1, 2, 4}` against node index `0 … 7`. The value is the
digit's `e`, `r` or `s` bit -- exactly what the corresponding circuit table holds. -/
""")
for tag, sel in SEL.items():
    for k in range(8):
        v = (REV[k] // sel) % 2
        print(f"theorem digitBit_{tag}_n{k} : digitBit {sel} ({NODES[k]} : F) = {v} := by")
        print(f"  norm_num [digitBit, (bbitrev (F := F)).{proj(k)}, "
              f"(bval3 (F := F)).{proj(REV[k])}]")
        print()

print('''/-! ### From the circuit's bit list to `reconstruct*`

`E2BitSum*` proves `e = bitsLE [w₀ … w₂₅₅]` over the circuit's wires, in `ers` order. The
specification's `reconstructE` folds most-significant-digit-first over the *loop*-order digit
list. `reconstructExponent_reverse` reconciles the two weightings; these three specialise it to
`digitBit`, so the assembly's only remaining job is to replace each `wₖ`. -/

private theorem recon (us : List F) (sel : Nat) (f : Nat → F)
    (hf : ∀ u : F, f (val3 (bitrev3 u)) = digitBit sel u) :
    reconstructExponent ((us.map bitrev3).map val3) f
      = bitsLE (us.reverse.map (digitBit sel)) := by
  have hmap : (us.map bitrev3).map val3 = (us.reverse.map (fun u => val3 (bitrev3 u))).reverse := by
    simp [List.map_map, List.map_reverse, Function.comp_def]
  rw [hmap, reconstructExponent_reverse, List.map_map]
  simp only [Function.comp_def, hf]

theorem reconstructE_digitBit (us : List F) :
    reconstructE ((us.map bitrev3).map val3) = bitsLE (us.reverse.map (digitBit 1)) := by
  unfold reconstructE
  refine recon us 1 _ fun u => ?_
  simp [digitBit]

theorem reconstructR_digitBit (us : List F) :
    reconstructR ((us.map bitrev3).map val3) = bitsLE (us.reverse.map (digitBit 2)) := by
  unfold reconstructR
  exact recon us 2 _ fun _ => rfl

theorem reconstructS_digitBit (us : List F) :
    reconstructS ((us.map bitrev3).map val3) = bitsLE (us.reverse.map (digitBit 4)) := by
  unfold reconstructS
  exact recon us 4 _ fun _ => rfl

end ECDSA2''')
