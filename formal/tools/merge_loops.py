#!/usr/bin/env python3
"""Merge per-assertion loop lemmas into one Lean module.

Usage: merge_loops.py BATCH_NAME file1.lean file2.lean ... > out.lean

`gen_loop_meaning.py` emits one self-contained module per assertion, which is the right unit to
generate and to debug but the wrong unit to build: 768 modules each pay the `import Mathlib`
floor. Batching amortises that.

`hpL` is emitted `private` so that batches can coexist -- private names are mangled with the
module name, so importing two batches into the same file does not clash.
"""
import re
import sys


def body(path):
    """Everything from the first non-`hpL` theorem to the closing `end`."""
    src = open(path).read()
    i = src.index("\ntheorem ", src.index("theorem hpL"))
    j = src.rindex("\nend Ecdsa2.Meaning")
    return src[i + 1 : j].rstrip()


def main():
    name, files = sys.argv[1], sys.argv[2:]
    P = 115792089210356248762697446949407573530086143415290314195533631308867097853951
    bodies = [body(f) for f in files]
    names = [re.match(r"theorem (\S+)", b).group(1) for b in bodies]
    print(f"""-- Generated by `formal/tools/merge_loops.py`. Do not edit.
import quadcert.Bridge.Ecdsa2.E2Meaning
import ECDSA.EcdsaV2

set_option maxRecDepth 4000000
set_option maxHeartbeats 4000000

/-!
# Loop rounds, batch `{name}`

{len(bodies)} of the 768 `slice_w*` assertions, each saying that one coordinate of one
accumulator step is `addE (doubleE acc) mux` -- the specification's operation, on the deployed
circuit's own wires. Generated by `formal/tools/gen_loop_meaning.py`; see that file for how the
mux boundary is found and why the cone is cut there.

Lemmas: {", ".join(names)}.
-/

namespace Ecdsa2.Meaning

open Quadcert Quadcert.Gen.Ecdsa2

variable {{F : Type}} [Field F] [CharP F p256]

private theorem hpL : ({P} : F) = 0 := by
  exact_mod_cast CharP.cast_eq_zero F {P}

{(chr(10) * 2).join(bodies)}

end Ecdsa2.Meaning""")


main()
