#!/usr/bin/env python3
"""Merge per-round mux lemmas into one Lean module.

Usage: merge_muxes.py BATCH_NAME file1.lean file2.lean ... > out.lean

Same reason as `merge_loops.py`: one module per lemma is the right unit to generate and debug
and the wrong unit to build, because each pays the `import Mathlib` floor. `hpM` is `private`
so batches can be imported side by side.
"""
import re
import sys


def body(path):
    """Everything from the first non-`hpM` theorem to the closing `end`."""
    src = open(path).read()
    i = src.index("\ntheorem ", src.index("theorem hpM"))
    j = src.rindex("\nend Ecdsa2.Meaning")
    return src[i + 1 : j].rstrip()


def main():
    name, files = sys.argv[1], sys.argv[2:]
    P = 115792089210356248762697446949407573530086143415290314195533631308867097853951
    bodies = [body(f) for f in files]
    names = [re.match(r"theorem (\S+)", b).group(1) for b in bodies]
    print(f"""-- Generated by `formal/tools/merge_muxes.py`. Do not edit.
import quadcert.Bridge.Ecdsa2.E2Meaning
import ECDSA.EcdsaV2

set_option maxRecDepth 4000000
set_option maxHeartbeats 2000000

/-!
# Round table lookups, batch `{name}`

{len(bodies)} of the 256 rounds. Each says that the triple of wires the corresponding loop-round
lemmas leave opaque *is* `optPoint` of that round's digit -- the fact those lemmas were cut
short of. Generated by `formal/tools/gen_mux_meaning.py`.

Lemmas: {", ".join(names)}.
-/

namespace Ecdsa2.Meaning

open Quadcert Quadcert.Gen.Ecdsa2

variable {{F : Type}} [Field F] [CharP F p256]

private theorem hpM : ({P} : F) = 0 := by
  exact_mod_cast CharP.cast_eq_zero F {P}

{(chr(10) * 2).join(bodies)}

end Ecdsa2.Meaning""")


main()
