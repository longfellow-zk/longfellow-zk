#!/usr/bin/env python3
"""Emit the remaining `soundness_of_v2` bridges that are not the loop.

Usage: gen_rest.py OUTDIR

Writes two modules:

* `E2Recon.lean` -- `he`, `hr`, `hsi`. `E2BitSum*` proves `e = bitsLE [w₀ … w₂₅₅]` over the
  circuit's wires; the 256 `bits_k` lemmas say each `wₖ` is the digit's `e`/`r`/`s` bit; and
  `ECDSA2.reconstruct*_digitBit` converts the specification's most-significant-first fold into
  the same least-significant-first sum. Needs only chunk 3 of the assertions.

* `E2Small.lean` -- `hpre`, `hax`, `haz`, `hrxi`, `hpki`, `hpkc`, `hrc`. All of these are
  already proved as `Ecdsa2Meaning` lemmas or as `E2SliceX` slice lemmas; the work here is
  assertion plumbing and two `addE_comm` rewrites, because the circuit computes `PK + R` and
  `G + R` where `ValidPreComputationExact` writes `R + PK` and `R + G`.

Assertion indices are read from the sidecar dump rather than hard-coded; the chunk sizes are the
`Ecdsa2Asserts*` lengths.
"""
import sys

B = 0x5AC635D8AA3A93E7B3EBBD55769886BC651D06B0CC53B0F63BCE3C3E27D2604B
GX = 0x6B17D1F2E12C4247F8BCE6E563A440F277037D812DEB33A0F4A13945D898C296
GY = 0x4FE342E2FE1A7F9B8EE7EB4A7C0F9E162BCE33576B315ECECBB6406837BF51F5
CHUNKS = [198, 196, 196, 240, 218]

# Layout positions, from `DUMP_LAYOUT`.
# Input positions are emitted as names from the generated `E2Layout.lean` rather than as
# the numerals they resolve to, so the circuit's own `LayoutBuilder` table is what fixes
# them and a reordered allocator changes one generated file instead of silently pointing
# these theorems at the wrong wire.
PKX, PKY, E, RX, RY = "Layout.pkx", "Layout.pky", "Layout.e", "Layout.rx", "Layout.ry"
PKXINV, RXINV, NMSINV = "Layout.pkxinv", "Layout.rxinv", "Layout.nmsinv"
INTX0, INTY0, INTZ0 = "(Layout.intx 0)", "(Layout.inty 0)", "(Layout.intz 0)"

# `us` is loop order: `us k = ers (255 - k)`.
US = [f"inputs (Layout.ers {255 - k})" for k in range(256)]
VS = [f"inputs (Layout.ers {k})" for k in range(256)]   # `us.reverse`, i.e. ers order

HEAD = """-- Generated by `formal/tools/gen_rest.py`. Do not edit.
"""

VAR = """
namespace Ecdsa2.Assembly

open Quadcert Quadcert.Gen.Ecdsa2 Ecdsa2.Meaning ECDSA2

variable {F : Type} [Field F] [CharP F p256]
"""


def chunk_destructure(c):
    names = ", ".join(f"c{c}_{j}" for j in range(CHUNKS[c]))
    return (f"  simp only [asserts_{c}, List.forall_mem_cons, List.forall_mem_nil] at H{c}\n"
            f"  obtain ⟨{names}, -⟩ := H{c}")


ASSERT_PRELUDE = """  have H := Ecdsa2.assertions_zero inputs hacc
  simp only [RawCircuit.toRecs, List.forall_mem_map,
    show (raw.asserts) = asserts_0 ++ asserts_1 ++ asserts_2 ++ asserts_3 ++ asserts_4 from rfl,
    List.forall_mem_append] at H
  obtain ⟨⟨⟨⟨H0, H1⟩, H2⟩, H3⟩, H4⟩ := H"""


def recon(outdir):
    imports = "\n".join(
        ["import quadcert.Gen.E2.E2Layout", "import quadcert.Gen.E2.E2BitSumE", "import quadcert.Gen.E2.E2BitSumRx",
         "import quadcert.Gen.E2.E2BitSumNms", "import quadcert.Bridge.Ecdsa2.E2Digits"]
        + [f"import quadcert.Gen.E2.E2BitB{k:02d}" for k in range(16)]
        + ["import ECDSA.BitTable"])

    digits = ", ".join(f"hd{k}" for k in range(256))
    bits = "\n".join(
        f"  obtain ⟨e{k}, r{k}, s{k}⟩ := bits_{k} inputs hone hd{k}" for k in range(256))
    erw = ", ".join(f"e{k}" for k in range(256))
    rrw = ", ".join(f"r{k}" for k in range(256))
    srw = ", ".join(f"s{k}" for k in range(256))
    us = ", ".join(US)
    vs = ", ".join(VS)

    body = f'''{HEAD}{imports}

set_option maxRecDepth 4000000
set_option maxHeartbeats 4000000

/-!
# `he`, `hr`, `hsi`: the three bit sums are the specification's reconstructions

The bit-sum lemmas prove `e = bitsLE [w₀ … w₂₅₅]` with the `wₖ` left opaque -- that cut is what
kept `ring` inside its budget. The `bits_k` lemmas say what each `wₖ` is, and
`ECDSA2.reconstructE_digitBit` reconciles the weightings: `reconstructE` folds
most-significant-digit-first over the loop-order digit list, while the circuit sums
least-significant-bit-first over `ers` order, and reversing the list is exactly the difference.
-/
{VAR}
/-- The digits in **loop order**: `usList k = ers (255 - k)`, since `circuit.rs` runs
    `i = 255 … 0`. This is the order `soundness_of_v2` expects. -/
def usList (inputs : Nat → F) : List F := [{us}]

theorem usList_reverse (inputs : Nat → F) :
    ([{vs}] : List F).reverse = usList inputs := by
  simp only [usList]
  rfl

theorem recon_ok (inputs : Nat → F) (hone : inputs 0 = 1)
    (hacc : Accepts (Ecdsa2.circuit F) inputs) :
    reconstructE (((usList inputs).map ECDSA2.bitrev3).map val3) = inputs {E} ∧
      reconstructR (((usList inputs).map ECDSA2.bitrev3).map val3) = inputs {RX} ∧
      reconstructS (((usList inputs).map ECDSA2.bitrev3).map val3) * inputs {NMSINV} = 1 := by
  obtain ⟨{digits}⟩ := digits_tuple inputs hone hacc
{ASSERT_PRELUDE}
{chunk_destructure(3)}
  have hbe := bitsum_e_eq inputs hone c3_180
  have hbr := bitsum_rx_eq inputs hone c3_181
  have hbs := bitsum_nmsinv inputs hone c3_182
{bits}
  rw [← usList_reverse inputs]
  refine ⟨?_, ?_, ?_⟩
  · rw [ECDSA2.reconstructE_digitBit, List.reverse_reverse, hbe]
    simp only [List.map_cons, List.map_nil, Layout.ers, {erw}]
  · rw [ECDSA2.reconstructR_digitBit, List.reverse_reverse, hbr]
    simp only [List.map_cons, List.map_nil, Layout.ers, {rrw}]
  · rw [ECDSA2.reconstructS_digitBit, List.reverse_reverse]
    rw [← hbs]
    simp only [List.map_cons, List.map_nil, Layout.ers, {srw}]

end Ecdsa2.Assembly
'''
    open(outdir + "/E2Recon.lean", "w").write(body)


def small(outdir):
    clears = " ".join([f"c3_{j}" for j in range(CHUNKS[3])]
                      + [f"c4_{j}" for j in range(CHUNKS[4])])
    imports = "\n".join([
        "import quadcert.Gen.E2.E2Layout",
        "import quadcert.Gen.Ecdsa2.Ecdsa2Meaning",
        "import quadcert.Gen.E2.E2SliceX",
        "import ECDSA.EcdsaV2",
    ])
    q = " ".join(f"(hq{j} : pre.getD {j} 0 = inputs (Layout.pre {j}))" for j in range(8))

    body = f'''{HEAD}{imports}

set_option maxRecDepth 4000000
set_option maxHeartbeats 4000000

/-!
# The small bridges

`hpre`, `hax`, `haz`, `hrxi`, `hpki`, `hpkc`, `hrc`. Every one of these is already a proved
meaning lemma -- the eleven non-`IsDigit` lemmas `meaning_gen` emits, plus the eight slice
lemmas in `E2SliceX`. What is left is assertion plumbing and two `addE_comm` rewrites:
`circuit.rs` computes `PK + R` and `G + R` where `ValidPreComputationExact` writes `R + PK` and
`R + G`.
-/
{VAR}
theorem small_ok (inputs : Nat → F) (hone : inputs 0 = 1)
    (pk : AffinePoint F) (rx ry : F) (pre : List F) (params : CurveParameters F)
    (ha : params.a = -3) (hb : params.b = ({B} : F))
    (hgx : params.gx = ({GX} : F)) (hgy : params.gy = ({GY} : F))
    (hpkx : pk.X = inputs {PKX}) (hpky : pk.Y = inputs {PKY})
    (hrx : rx = inputs {RX}) (hry : ry = inputs {RY})
    (hlen : pre.length = 8) {q}
    (hacc : Accepts (Ecdsa2.circuit F) inputs) :
    ValidPreComputationExact pk rx ry pre params ∧
      inputs {INTX0} = 0 ∧ inputs {INTZ0} = 0 ∧
      rx * inputs {RXINV} = 1 ∧ pk.X * inputs {PKXINV} = 1 ∧
      pk.IsOnCurve params ∧ AffinePoint.IsOnCurve ⟨rx, ry⟩ params := by
{ASSERT_PRELUDE}
{chunk_destructure(3)}
{chunk_destructure(4)}
  have sx0 := sliceX_0 inputs hone params ha hb c3_183
  have sy0 := sliceY_0 inputs hone params ha hb c3_184
  have sx1 := sliceX_1 inputs hone params ha hb c4_201
  have sy1 := sliceY_1 inputs hone params ha hb c4_202
  have sx2 := sliceX_2 inputs hone params ha hb c4_203
  have sy2 := sliceY_2 inputs hone params ha hb c4_204
  have sx3 := sliceX_3 inputs hone params ha hb c4_205
  have sy3 := sliceY_3 inputs hone params ha hb c4_206
  have hcpk := m25611 inputs hone c4_207
  have hcr := m5640 inputs hone c4_208
  have hax := m17885 inputs hone c4_216
  have haz := m249 inputs hone c4_217
  have hrxi := m25822 inputs hone c4_214
  have hpki := m16524 inputs hone c4_213
  -- Drop the 458 assertion hypotheses now that the fourteen that matter have been named. The
  -- closing `assumption` would otherwise unify each goal against every one of them, and those
  -- are large `interpDag` terms: with them in scope this times out at `whnf`.
  clear {clears} H0 H1 H2
  -- `simp only`, not `rw`: `AffinePoint.toProjective` occurs twice per goal and `rw` rewrites
  -- only the first, leaving the record projections unreduced.
  simp only [ValidPreComputationExact, IsPointEquality, AffinePoint.toProjective,
    hq0, hq1, hq2, hq3, hq4, hq5, hq6, hq7, hgx, hgy, hpkx, hpky, hrx, hry]
  -- `simp only` unfolds `IsPointEquality`, so the conjunction is flatter than the source
  -- suggests. Splitting with `repeat'` rather than one `refine ⟨…⟩` keeps this insensitive to
  -- exactly how far it unfolded.
  repeat' apply And.intro
  all_goals first
    | assumption
    -- `GR` and `RPK`: the circuit adds `G + R` and `PK + R`, the specification writes them
    -- the other way round
    | (rw [addE_comm]; assumption)
    -- `params.a * x` against the circuit's `-3 * x`: the same polynomial, not the same term
    | (simp only [AffinePoint.IsOnCurve, ha, hb, hpkx, hpky, hrx, hry,
         Layout.pkx, Layout.pky, Layout.rx, Layout.ry]
       first
         | linear_combination hcpk
         | linear_combination hcr)

end Ecdsa2.Assembly
'''
    open(outdir + "/E2Small.lean", "w").write(body)


outdir = sys.argv[1]
recon(outdir)
small(outdir)
print(f"wrote {outdir}/E2Recon.lean and {outdir}/E2Small.lean")
