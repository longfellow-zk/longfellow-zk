#!/usr/bin/env python3
"""Emit `E2Ecdsa.lean`: the deployed circuit's assertions imply the ECDSA specification.

Usage: gen_final.py OUTDIR

This is the composition. Everything it uses is a theorem about the *deployed* quad circuit:

* `digits_ok`            (`E2Digits`)  -> `hdig`
* `loop_ok`              (`E2LoopOk`)  -> `hloop`
* `recon_ok`             (`E2Recon`)   -> `he`, `hr`, `hsi`
* `small_ok`             (`E2Small`)   -> `hpre`, `hax`, `haz`, `hrxi`, `hpki`, `hpkc`, `hrc`

* `cmp_ok`               (`E2Cmp`)     -> `hrlt`, `hslt`

Every hypothesis of `soundness_of_v2` that is a statement about the circuit is now discharged
from `Accepts` alone.

The four curve facts (`h_G_on`, `h_pk_order`, `h_G_order`, `h_R_order`) stay hypotheses by
design: `h_pk_order` says the public key is killed by the group order, which needs
`#E(𝔽_p) = n` -- a point-counting fact, not a circuit fact.
"""
import sys

B = 0x5AC635D8AA3A93E7B3EBBD55769886BC651D06B0CC53B0F63BCE3C3E27D2604B
GX = 0x6B17D1F2E12C4247F8BCE6E563A440F277037D812DEB33A0F4A13945D898C296
GY = 0x4FE342E2FE1A7F9B8EE7EB4A7C0F9E162BCE33576B315ECECBB6406837BF51F5
ORDER = 0xFFFFFFFF00000000FFFFFFFFFFFFFFFFBCE6FAADA7179E84F3B9CAC2FC632551

PKX, PKY, E, RX, RY = 1, 2, 3, 4, 5
PKXINV, RXINV, NMSINV, PRE0, INT0 = 262, 263, 264, 266, 274

# Loop order: chain position `j` is circuit round `255 - j`.
US = [f"inputs {6 + 255 - j}" for j in range(256)]
WX = [f"inputs {INT0 + 3 * (255 - j)}" for j in range(256)]
WY = [f"inputs {INT0 + 1 + 3 * (255 - j)}" for j in range(256)]
WZ = [f"inputs {INT0 + 2 + 3 * (255 - j)}" for j in range(256)]
PRE = ", ".join(f"inputs {PRE0 + k}" for k in range(8))


def main():
    outdir = sys.argv[1]
    src = f'''-- Generated by `formal/tools/gen_final.py`. Do not edit.
import quadcert.Gen.E2.E2LoopOk
import quadcert.Gen.E2.E2Recon
import quadcert.Gen.E2.E2Small
import quadcert.Gen.E2.E2Cmp
import ECDSA.CmpBridge

set_option maxRecDepth 4000000
set_option maxHeartbeats 4000000

/-!
# The deployed ECDSA2 circuit implies the ECDSA specification

Every hypothesis of `ECDSA2.soundness_of_v2` that is a statement *about the circuit* is
discharged from `Accepts (Ecdsa2.circuit F) inputs` alone, through the five assembly bridges.
What remains as hypotheses are exactly the things that are not circuit facts:

* the four curve facts, which need the group order of `E(𝔽_p)` -- `h_pk_order` says the public
  key is killed by that order, and no circuit assertion can establish it;
* `horder`, pinning the abstract `order` to P-256's `n`, together with the accompanying
  `Fact (Nat.Prime order)` instance.

The input layout is the one place meaning is *chosen* rather than checked, and it enters here:
position 1/2 is the public key, 3 the message hash, 4/5 the point `R`, 6…261 the digits,
262…264 the three inverses, 266…273 the precomputed points, and 274 + 3k the k-th stored
accumulator.
-/

namespace Ecdsa2.Assembly

open Quadcert Quadcert.Gen.Ecdsa2 Ecdsa2.Meaning ECDSA2

variable {{F : Type}} [Field F] [CharP F p256]

/-- The eight precomputed coordinates, in `ValidPreComputationExact` order. -/
def preList (inputs : Nat → F) : List F := [{PRE}]

/-- The first 255 stored accumulators, in loop order. `soundness_of_v2` wants them split from
    the last one, which `ax_zero` / `az_zero` constrain; `wxsList ++ [inputs 274]` is the
    256-element list `loop_ok` proves about, and the two are the same term. -/
def wxsList (inputs : Nat → F) : List F := [{", ".join(WX[:-1])}]
def wysList (inputs : Nat → F) : List F := [{", ".join(WY[:-1])}]
def wzsList (inputs : Nat → F) : List F := [{", ".join(WZ[:-1])}]

theorem ecdsa2_sound
    (inputs : Nat → F) (hone : inputs 0 = 1)
    (params : CurveParameters F) [(params.toMathlib).IsElliptic]
    [CurveHasNoPointsOfOrder2 params] (order : Nat) [Fact (Nat.Prime order)]
    (ha : params.a = -3) (hb : params.b = ({B} : F))
    (hgx : params.gx = ({GX} : F)) (hgy : params.gy = ({GY} : F))
    (hk : params.kBits = 256)
    (horder : order = {ORDER})
    (hacc : Accepts (Ecdsa2.circuit F) inputs)
    (h_G_on : ProjectivePoint.IsOnCurve
      ({{ X := params.gx, Y := params.gy : AffinePoint F }}).toProjective params)
    (h_pk_order : bsmul (padBits (natToBits order) params.kBits)
      ({{ X := inputs {PKX}, Y := inputs {PKY} : AffinePoint F }}).toProjective params = infinityPoint)
    (h_G_order : ProjectiveEquiv (bsmul (padBits (natToBits order) params.kBits)
      ({{ X := params.gx, Y := params.gy : AffinePoint F }}).toProjective params) infinityPoint)
    (h_R_order : ProjectiveEquiv (bsmul (padBits (natToBits order) params.kBits)
      ({{ X := inputs {RX}, Y := inputs {RY} : AffinePoint F }}).toProjective params) infinityPoint) :
    ∃ (r s e_nat : Nat),
      r = natR (((usList inputs).map ECDSA2.bitrev3).map val3) ∧
      s = order - natS (((usList inputs).map ECDSA2.bitrev3).map val3) ∧
      e_nat = natE (((usList inputs).map ECDSA2.bitrev3).map val3) ∧
      StandardEcdsaVerify ({{ X := inputs {PKX}, Y := inputs {PKY} : AffinePoint F }})
        e_nat r s order params := by
  obtain ⟨hrlt, hslt⟩ := cmp_ok inputs hone hacc
  rw [← horder] at hrlt hslt
  have hdig := digits_ok inputs hone hacc
  have hloop := loop_ok inputs hone ({{ X := inputs {PKX}, Y := inputs {PKY} : AffinePoint F }})
    (inputs {RX}) (inputs {RY}) (preList inputs) params ha hb (by rw [hgx]; norm_num)
    (by rw [hgy]; norm_num) rfl rfl rfl rfl rfl rfl rfl rfl rfl rfl rfl rfl hacc
  obtain ⟨he, hr, hsi⟩ := recon_ok inputs hone hacc
  obtain ⟨hpre, hax, haz, hrxi, hpki, hpkc, hrc⟩ :=
    small_ok inputs hone ({{ X := inputs {PKX}, Y := inputs {PKY} : AffinePoint F }})
      (inputs {RX}) (inputs {RY}) (preList inputs) params ha hb hgx hgy rfl rfl rfl rfl
      rfl rfl rfl rfl rfl rfl rfl rfl rfl hacc
  refine soundness_of_v2 params order
    ({{ X := inputs {PKX}, Y := inputs {PKY} : AffinePoint F }})
    (inputs {E}) (inputs {RX}) (inputs {RY}) (inputs {RXINV}) (inputs {NMSINV}) (inputs {PKXINV})
    (usList inputs) (wxsList inputs) (wysList inputs) (wzsList inputs)
    (preList inputs) (inputs {INT0}) (inputs {INT0 + 1}) (inputs {INT0 + 2})
    (by rw [hk]; rfl) (by rw [hk]; rfl) (by rw [hk]; rfl) (by rw [hk]; rfl) rfl
    ?_ hloop hax haz hpre he hr hpkc hrc hrxi hsi hpki hrlt hslt
    h_G_on h_pk_order h_G_order h_R_order
  -- `digitWires` is `ers` order and `usList` is loop order: the same 256 wires, reversed.
  intro u hu
  refine hdig u ?_
  simp only [digitWires]
  have h2 : u ∈ (usList inputs).reverse := List.mem_reverse.mpr hu
  rwa [← usList_reverse inputs, List.reverse_reverse] at h2

/-! ### The same, from the committed bytes

`ecdsa2_sound` is stated over `Ecdsa2.circuit`, which is a generated literal. `raw_from_bytes`
proves that whatever the pinned LFC3 pages decode to — extended by the sidecar's four advice
fields — *is* that literal, so the theorem transfers to the artifact with one rewrite. This is
the form an auditor should read: its hypothesis mentions the committed bytes, not anything a
generator wrote down. -/

theorem ecdsa2_sound_of_bytes
    (c : Lfc3.DecodedCircuit)
    (hdec : Lfc3.decode Lfc3.p256 Quadcert.Gen.Ecdsa2.packedInput
      Quadcert.Gen.Ecdsa2.deltaTrees = .ok c)
    (inputs : Nat → F) (hone : inputs 0 = 1)
    (params : CurveParameters F) [(params.toMathlib).IsElliptic]
    [CurveHasNoPointsOfOrder2 params] (order : Nat) [Fact (Nat.Prime order)]
    (ha : params.a = -3) (hb : params.b = ({B} : F))
    (hgx : params.gx = ({GX} : F)) (hgy : params.gy = ({GY} : F))
    (hk : params.kBits = 256)
    (horder : order = {ORDER})
    (hacc : Accepts ((c.toRaw advice).toQuad (Ecdsa2.consts F)) inputs)
    (h_G_on : ProjectivePoint.IsOnCurve
      ({{ X := params.gx, Y := params.gy : AffinePoint F }}).toProjective params)
    (h_pk_order : bsmul (padBits (natToBits order) params.kBits)
      ({{ X := inputs {PKX}, Y := inputs {PKY} : AffinePoint F }}).toProjective params = infinityPoint)
    (h_G_order : ProjectiveEquiv (bsmul (padBits (natToBits order) params.kBits)
      ({{ X := params.gx, Y := params.gy : AffinePoint F }}).toProjective params) infinityPoint)
    (h_R_order : ProjectiveEquiv (bsmul (padBits (natToBits order) params.kBits)
      ({{ X := inputs {RX}, Y := inputs {RY} : AffinePoint F }}).toProjective params) infinityPoint) :
    ∃ (r s e_nat : Nat),
      r = natR (((usList inputs).map ECDSA2.bitrev3).map val3) ∧
      s = order - natS (((usList inputs).map ECDSA2.bitrev3).map val3) ∧
      e_nat = natE (((usList inputs).map ECDSA2.bitrev3).map val3) ∧
      StandardEcdsaVerify ({{ X := inputs {PKX}, Y := inputs {PKY} : AffinePoint F }})
        e_nat r s order params := by
  rw [raw_from_bytes c hdec] at hacc
  exact ecdsa2_sound inputs hone params order ha hb hgx hgy hk horder hacc
    h_G_on h_pk_order h_G_order h_R_order

end Ecdsa2.Assembly
'''
    open(outdir + "/E2Ecdsa.lean", "w").write(src)
    print(f"wrote {outdir}/E2Ecdsa.lean")


main()
