#!/usr/bin/env python3
"""Merge per-round bit-table lemmas into one Lean module.

Usage: merge_bits.py BATCH_NAME file1.lean file2.lean ... > out.lean

The third of these mergers, after `merge_loops.py` and `merge_muxes.py`, and missing until now:
`gen_all_bits.sh` emitted 256 single-lemma modules and nothing batched them, so the
`E2BitB00..15` that `E2Recon` and `E2Cmp` import were never produced.

Same reason as the other two -- one module per lemma is the right unit to generate and debug and
the wrong unit to build, since each pays the `import Mathlib` floor.  `hpB` is `private` so the
batches can be imported side by side; `gen_bit_meaning.py` already emits it that way, and the
name differs per family (`hpL`, `hpM`, `hpB`) for exactly that reason.
"""
import re
import sys


def body(path):
    """Everything from the first non-`hpB` theorem to the closing `end`."""
    src = open(path).read()
    i = src.index("\ntheorem ", src.index("theorem hpB"))
    j = src.rindex("\nend Ecdsa2.Meaning")
    return src[i + 1 : j].rstrip()


def main():
    name, files = sys.argv[1], sys.argv[2:]
    P = 115792089210356248762697446949407573530086143415290314195533631308867097853951
    bodies = [body(f) for f in files]
    names = [re.match(r"theorem (\S+)", b).group(1) for b in bodies]
    print(f"""-- Generated by `formal/tools/merge_bits.py`. Do not edit.
import quadcert.Bridge.Ecdsa2.E2Meaning
import ECDSA.BitTable

set_option maxRecDepth 4000000
set_option maxHeartbeats 1000000

/-!
# Round bit tables, batch `{name}`

{len(bodies)} of the 256 rounds. Each identifies the three wires that `e_eq`, `rx_eq` and
`nmsinv` leave opaque with that round's digit bits -- the fact the bit-sum lemmas were cut short
of. Generated by `formal/tools/gen_bit_meaning.py`.

Lemmas: {", ".join(names)}.
-/

namespace Ecdsa2.Meaning

open Quadcert Quadcert.Gen.Ecdsa2

variable {{F : Type}} [Field F] [CharP F p256]

private theorem hpB : ({P} : F) = 0 := by
  exact_mod_cast CharP.cast_eq_zero F {P}

{(chr(10) * 2).join(bodies)}

end Ecdsa2.Meaning""")


main()
