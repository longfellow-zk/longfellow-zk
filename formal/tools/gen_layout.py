"""Emit `E2Layout.lean`: names for the circuit's input positions, derived from the artifact.

Usage: gen_layout.py OUTDIR [--artifact Ecdsa2] [--namespace Ecdsa2.Layout]

Why this exists
---------------

The assembly bridges used to write input positions as bare numerals -- `inputs 1`, `inputs 266`,
`inputs 1039` -- with the numbers transcribed by hand into Python constants:

    PKX, PKY, E, RX, RY = 1, 2, 3, 4, 5
    PKXINV, RXINV, NMSINV, PRE0, INT0 = 262, 263, 264, 266, 274

That made the emitted Lean 99% circuit-derived: 1,853 position references against 14 curve
constants, so none of it could be committed and hand-maintained.  Worse, nothing checked the
transcription.  If the allocator reorders inputs, position 1 stops being `pkx` and every
affected theorem becomes quietly false rather than failing to build.

The circuit already names every input.  `LayoutBuilder::record` in `ecdsa2_artifacts.rs` tags
each position (`pkx`, `ers7`, `intx255`), and `cert::emit_lean` writes the table into
`{Artifact}Data.lean`.  This reads that table back and turns it into definitions, so the bridges
say `inputs pkx` and `inputs (intx 255)`.  The numbers then live in exactly one generated file
and the mathematics above them is committable.

**Every name is an `abbrev`, not a `def`.**  The bridges that say `inputs e` have to rewrite with
generated lemmas that say `inputs 3` -- `bitsum_e_eq` concludes `inputs 3 = bitsLE [...]` -- and
`rw` and `simp` match at reducible transparency.  A plain `def e : Nat := 3` is opaque there, so
`rw [hbe]` reported "did not find an occurrence of the pattern" against a goal that was
definitionally exactly right.  `abbrev` is reducible, which is what lets the committed, symbolic
layer and the regenerated, numeric one meet without either having to change.

Families are recognised, not hardcoded: positions sharing a name prefix with a contiguous index
range and a constant stride become `def f (i : Nat) : Nat := base + stride * i`.  That is what
makes `intx`/`inty`/`intz` -- interleaved at stride 3 -- come out as arithmetic rather than as
three 256-element tables.
"""
import argparse, os, re, sys, collections

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)


def read_layout(artifact):
    """`[(position, name)]` from the generated `{artifact}Data.lean`."""
    p = os.path.join(ROOT, "circuits", "quadcert", "Gen", artifact, f"{artifact}Data.lean")
    if not os.path.exists(p):
        raise SystemExit(
            f"no artifact at {p}\n"
            f"Generate it first:  tools/regen_artifact.sh "
            f"{'ecdsa2' if artifact == 'Ecdsa2' else 'sha256-p256'}")
    m = re.search(r'layout := \[(.*?)\]\n', open(p).read(), re.S)
    if not m:
        raise SystemExit(f"{p} has no `layout :=` table")
    return [(int(a), b) for a, b in re.findall(r'\((\d+),\s*"([^"]+)"\)', m.group(1))]


def families(layout):
    """Split names into scalars and indexed families.

    A family is a name prefix whose indices are exactly `0 .. n-1` and whose positions form an
    arithmetic progression.  Anything else stays a scalar, one definition per position, so an
    irregular layout degrades to a table instead of being silently mis-described.
    """
    groups = collections.defaultdict(list)
    for pos, name in layout:
        g = re.match(r'^(.*?)(\d*)$', name)
        base, idx = g.group(1), g.group(2)
        groups[base].append((pos, int(idx) if idx else None, name))

    scalars, fams = [], []
    for base, members in sorted(groups.items(), key=lambda kv: min(p for p, _, _ in kv[1])):
        members.sort(key=lambda t: (t[1] if t[1] is not None else -1))
        if len(members) == 1 and members[0][1] is None:
            scalars.append((members[0][2], members[0][0]))
            continue
        idxs = [i for _, i, _ in members]
        poss = [p for p, _, _ in members]
        strides = {poss[k + 1] - poss[k] for k in range(len(poss) - 1)}
        if idxs == list(range(len(idxs))) and len(strides) == 1:
            fams.append((base, poss[0], strides.pop(), len(idxs)))
        else:
            scalars.extend((n, p) for p, _, n in members)
    return scalars, fams


def emit(layout, namespace, artifact):
    scalars, fams = families(layout)
    o = [f"-- Generated by `formal/tools/gen_layout.py` from `Gen/{artifact}/{artifact}Data.lean`.",
         "-- Do not edit.",
         "",
         "/-!",
         f"# Input positions of the `{artifact}` circuit",
         "",
         "Names for the circuit's input array, read off the `LayoutBuilder` table the compiler",
         "emitted.  The bridges above this file speak in these names, so a change to the input",
         "allocation shows up as a change *here* -- one generated file -- instead of silently",
         "redirecting a theorem to the wrong wire.",
         "",
         "They are `abbrev`s so that `rw` and `simp`, which match at reducible transparency, see",
         "`inputs e` and the generated lemmas' `inputs 3` as the same term.",
         "",
         f"{len(layout)} named positions, 0 .. {max(p for p, _ in layout)}.",
         "-/",
         "",
         f"namespace {namespace}",
         ""]
    for name, pos in scalars:
        o.append(f"abbrev {name} : Nat := {pos}")
    if fams:
        o.append("")
    for base, start, stride, n in fams:
        rhs = f"{start} + {'' if stride == 1 else f'{stride} * '}i"
        o.append(f"/-- `{base}0 … {base}{n - 1}` at positions {start}"
                 f"{f', stride {stride}' if stride != 1 else f' … {start + n - 1}'}. -/")
        o.append(f"abbrev {base} (i : Nat) : Nat := {rhs}")
        o.append("")
    o.append(f"end {namespace}")
    return "\n".join(o) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("outdir")
    ap.add_argument("--artifact", default="Ecdsa2")
    ap.add_argument("--namespace", default=None)
    a = ap.parse_args()
    ns = a.namespace or f"{a.artifact}.Layout"
    lay = read_layout(a.artifact)
    os.makedirs(a.outdir, exist_ok=True)
    out = os.path.join(a.outdir, f"{'E2' if a.artifact == 'Ecdsa2' else a.artifact}Layout.lean")
    open(out, "w").write(emit(lay, ns, a.artifact))
    sc, fm = families(lay)
    print(f"wrote {out}: {len(sc)} scalars, {len(fm)} families, {len(lay)} positions")


if __name__ == "__main__":
    main()
