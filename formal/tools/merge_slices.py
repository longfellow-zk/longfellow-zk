#!/usr/bin/env python3
"""Merge the eight `slicing2` lemmas into `E2SliceX`.

Usage: merge_slices.py BATCH_NAME file1.lean ... > out.lean

The fourth merger, after loops, muxes and bits.  `gen_addE_meaning.py` emits one module per
lemma with a non-`private` `hp`, so concatenating them would clash on that name; the other
families already emit theirs private (`hpL`, `hpM`, `hpB`) for exactly this reason.  This
re-emits it once, private, and splices the bodies after it.
"""
import re
import sys


def body(path):
    """Everything from the first theorem after `hp` to the closing `end`."""
    src = open(path).read()
    i = src.index("\ntheorem ", src.index("theorem hp"))
    j = src.rindex("\nend Ecdsa2.Meaning")
    return src[i + 1 : j].rstrip()


def main():
    name, files = sys.argv[1], sys.argv[2:]
    P = 115792089210356248762697446949407573530086143415290314195533631308867097853951
    bodies = [body(f) for f in files]
    names = [re.match(r"theorem (\S+)", b).group(1) for b in bodies]
    print(f"""-- Generated by `formal/tools/merge_slices.py`. Do not edit.
import quadcert.Bridge.Ecdsa2.E2Meaning
import ECDSA.EcdsaV2

set_option maxRecDepth 4000000
set_option maxHeartbeats 2000000

/-!
# The `slicing2` assertions, batch `{name}`

{len(bodies)} lemmas. Each says that a `slicing2(w, pt)` assertion -- `pt.X = pt.Z * w.x` with
`pt` an `addE` of two affine points -- is one half of `ValidPreComputationExact`'s
`IsPointEquality`. Generated by `formal/tools/gen_addE_meaning.py`.

Lemmas: {", ".join(names)}.
-/

namespace Ecdsa2.Meaning

open Quadcert Quadcert.Gen.Ecdsa2

variable {{F : Type}} [Field F] [CharP F p256]

private theorem hp : ({P} : F) = 0 := by
  exact_mod_cast CharP.cast_eq_zero F {P}

{(chr(10) * 2).join(bodies)}

end Ecdsa2.Meaning""")


main()
