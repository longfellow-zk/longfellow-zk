import sys, os, pickle, re
SP = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, SP)
from gen_rnd import (nodes, ONE, statename, wname, bitpos, xlegs, sg, lname)
from emit_rnd import sigma_rows, maj_rows
import comp_rnd
NL = chr(10)
OUT = "/Users/abhi/Projects/longfellow-zk/formal/circuits/quadcert/Bridge/Sha256"
insts = pickle.load(open(os.path.join(SP, "rinsts.pkl"), "rb"))
H = (nodes, ONE, statename, wname, bitpos, xlegs, sigma_rows, maj_rows)
HDR = """import quadcert.Bridge.Sha256.S2Rnd{L}
import quadcert.Bridge.Sha256.S2State
import quadcert.Bridge.Sha256.S2EdgesRnd

set_option maxRecDepth 8000000
set_option maxHeartbeats 4000000

namespace Sha256Blk

open Quadcert Quadcert.Gen.Sha256Blk

variable {{F : Type}} [Field F]

"""
def one(d):
    p1, gs, wn = comp_rnd.make(d, H)
    p2, tag = comp_rnd.make2(d, H, gs, wn)
    p3 = comp_rnd.make3(d, H, gs, wn, tag)
    return p1 + NL + p2 + NL + p3
if __name__ == "__main__":
    which = sys.argv[1]
    if which == "all":
        LET = "ABCDEFGHIJKLMNOP"
        for i in range(16):
            chunk = insts[i*8:(i+1)*8]
            hdr = """/-
# Round steps {lo}-{hi} (`n = {n}`): the compression step over the deployed circuit

Generated by `tools/gen_comp_rnd.py`. Do not edit.

`rnd t` is `SHA256.sha256_soundness`'s `hrnd_e` (for `n = 6`) or `hrnd_a` (for `n = 7`) at round
`t`, phrased over `stateBits`/`wordBits` so the 64 rounds chain.
-/

""".format(lo=chunk[0]['t'], hi=chunk[-1]['t'], n=chunk[0]['n']) + HDR.format(L=LET[i])
            body = hdr + NL.join(one(d) for d in chunk) + NL + "end Sha256Blk" + NL
            open(os.path.join(OUT, f"S2CRnd{LET[i]}.lean"), "w").write(body)
            print(f"  S2CRnd{LET[i]}.lean  n={chunk[0]['n']} t={chunk[0]['t']}..{chunk[-1]['t']}  {body.count(NL)} lines")
    elif which == "probe":
        d6 = [x for x in insts if x['n']==6][0]; d7 = [x for x in insts if x['n']==7][0]
        open(os.path.join(OUT, "S2CRndProbe.lean"), "w").write(
            HDR.format(L="A") + one(d6) + NL + "end Sha256Blk" + NL)
        open(os.path.join(OUT, "S2CRndProbe7.lean"), "w").write(
            HDR.format(L="I") + one(d7) + NL + "end Sha256Blk" + NL)
        print("emitted probes")
