"""Emit one seam module per wrapping-sum assertion: the cone read as 32-bit arithmetic.

Per instance the chain is

    wrapW{c}_zero        the cone is `Π_{j<n} (got − (α^(2^32))^j · want) = 0`
    inj{op} × 4          each of `got`'s and `want`'s two operands is a power of α
    wrapM_of_prod_zero   the product vanishes at some factor
    wrap_nat_gf          therefore `E_want = E_got mod 2^32`

`E_got` is the sum of the addends' words plus, for the 128 round instances, the folded `α^(Kₜ)`
— which is why `n` counts `Kₜ` as an addend (a=7, e=6) and the bound `Σ B ≤ n·2^32` closes.

Usage: SHA_ARTIFACT=Sha256Gf2 python3 gen_gf2_seam.py [--out DIR] [--only CLASS:E]
"""
import sys, os, re, argparse
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_gf2_inj as I
from sha_parse import GEN, NAME

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
BRIDGE = os.path.join(ROOT, "circuits", "quadcert", "Bridge", "Sha256Gf2")

NEDGES = 6656
ROWGROUP = {}   # filled in `main` once the cone ordering is known

# (class tag, addend count, whether the class lemma takes `hin0`)
CLASSES = [("W2", 2, False), ("W4", 4, False), ("W6", 6, True), ("W7", 7, True), ("W6b", 6, True)]


def read_maps():
    """class tag -> {instance -> [template position -> artifact node]}, from Gf2WrapTmpl."""
    s = open(os.path.join(BRIDGE, "Gf2WrapTmpl.lean")).read()
    out = {}
    for tag, _, _ in CLASSES:
        m = re.search(rf"def map{tag} : Nat → Nat → Nat\n(.*?)\n\n", s, re.S)
        rows = re.findall(r"\|\s*(?:(\d+)|_)\s*=>\s*fun i => \(\[([\d,\s]+)\]", m.group(1))
        d = {}
        for e, (idx, body) in enumerate(rows):
            d[e] = [int(x) for x in body.replace(" ", "").split(",")]
        out[tag] = d
    return out


ROWMOD = [None]


def lean(tag, n, hin0, e, mp, B, FL, BD):
    """One seam theorem. `mp` is the instance's map; operands sit at positions 0…3."""
    ops = [mp[i] for i in range(4)]
    names = ["a", "b", "c", "d"]
    out = []
    A = out.append
    if ROWMOD[0]:
        A(f"import quadcert.Bridge.Sha256Gf2.{ROWMOD[0]}")
    else:
        for g in sorted({ROWGROUP[o] for o in ops}):
            A(f"import quadcert.Bridge.Sha256Gf2.Gf2Rows{g}")
    A("")
    A("/-!")
    A(f"# `{tag}` instance {e}: assertion node {mp[-1]}, as 32-bit arithmetic")
    A("")
    A(f"    got  = v{ops[0]} · v{ops[1]}")
    A(f"    want = v{ops[2]} · v{ops[3]}")
    A("")
    A(f"`n = {n}` addends. Generated by `gen_gf2_seam.py`; the only hypotheses left standing are")
    A("`hval` — which bit each injection factor injects — and its booleanity, both of which are")
    A("the word layer's obligation rather than this file's.")
    A("-/")
    A("")
    A("set_option maxRecDepth 8000000")
    A("set_option maxHeartbeats 1000000")
    A("")
    A("namespace Sha256Gf2")
    A("")
    A("open Quadcert Quadcert.Gen.Sha256Gf2 GF128")
    A("")
    A("variable {F : Type} [Field F] [CharP F 2]")
    A("")
    A(f"theorem seam{tag}_{e} (α : F) (hgen : IsGen α) (inputs : Nat → F) (hin0 : inputs 0 = 1)")
    A(f"    (hzb : ∀ e, e < {NEDGES} →")
    A("      interpDag (raw.toDag (consts α)) inputs (assertOfB e) = 0)")
    A(f"    (hz : interpDag (raw.toDag (consts α)) inputs (map{tag} {e} root{tag}) = 0) :")
    fl = {k: FL[o].replace("n ", f"nOf{o} α inputs ") for k, o in zip(names, ops)}
    A(f"    ({fl['c']}) + ({fl['d']}) = (({fl['a']}) + ({fl['b']})) % 2 ^ 32 := by")
    args = f"α hgen inputs" + (" hin0" if hin0 else "")
    A(f"  have hw := wrap{tag}_zero {args} {e} (by norm_num) hz")
    for i, (k, o) in enumerate(zip(names, ops)):
        A(f"  have h{i} : lvAt α inputs (map{tag} {e}) {i} = α ^ ({fl[k]}) := by")
        A(f"    show interpDag (raw.toDag (consts α)) inputs (map{tag} {e} {i}) = _")
        A(f"    rw [show map{tag} {e} {i} = {o} from rfl]")
        A(f"    exact injZ{o} α hgen inputs hin0 hzb")
    A("  rw [h0, h1, h2, h3, ← pow_add, ← pow_add] at hw")
    A(f"  obtain ⟨j, hj, hg⟩ := wrapM_of_prod_zero {n} _ _ _ hw")
    for k, o in zip(names, ops):
        A(f"  have hc{k} := inj{o}_lt (nOf{o} α inputs) (fun _ _ => bitOf_isBit _)")
    A("  have hC := lt_of_lt_of_le (Nat.add_lt_add hca hcb)")
    A(f"    (by norm_num : ({BD[ops[0]]} : Nat) + {BD[ops[1]]} ≤ {n} * 2 ^ 32)")
    # One of `want`'s two operands is always the constant squaring chain, whose exponent is the
    # literal `0`.  Summing its *strict* bound would give `2^32 + 1` and lose the `hP` the reader
    # needs, so the zero side is simplified away instead of bounded.
    zc, zd = fl['c'] == "0", fl['d'] == "0"
    assert zc != zd, "expected exactly one constant operand in `want`"
    keep, bnd = ("hcd", BD[ops[3]]) if zc else ("hcc", BD[ops[2]])
    A(f"  have hP : ({fl['c']}) + ({fl['d']}) < 2 ^ 32 :=")
    A(f"    lt_of_lt_of_le (by simpa using {keep}) (by norm_num : ({bnd} : Nat) ≤ 2 ^ 32)")
    A(f"  exact wrap_nat_gf α hgen {n} _ _ hC hP (bound_of_le {n} (by norm_num)) ⟨j, hj, hg⟩")
    A("")
    A("end Sha256Gf2")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=BRIDGE)
    ap.add_argument("--only")
    ap.add_argument("--rowmod")
    args = ap.parse_args()
    ROWMOD[0] = args.rowmod
    maps = read_maps()
    # the row-form modules are grouped 16 cones to a module, in sorted cone order
    import probe_inj as PI
    allops = set(PI.operands())
    for tag0, _, _ in CLASSES:
        for _e, _mp in maps[tag0].items():
            allops.update(_mp[:4])
    for idx, o in enumerate(sorted(allops)):
        ROWGROUP[o] = idx // 16
    B, FL, BD = {}, {}, {}
    bad = []
    written = 0
    for tag, n, hin0 in CLASSES:
        for e, mp in sorted(maps[tag].items()):
            if args.only and args.only != f"{tag}:{e}":
                continue
            for o in mp[:4]:
                if o not in B:
                    B[o] = I.build(o)
                    FL[o] = I.flat(B[o])
                    BD[o] = I.flat_bound(B[o])[2]
            g = BD[mp[0]] + BD[mp[1]]
            zs = [FL[o] == "0" for o in mp[:4]]
            w = sum(BD[o] for o, z in zip(mp[2:4], zs[2:4]) if not z)
            if g > n * 2 ** 32 or w > 2 ** 32 or zs[0] or zs[1] or zs[2] == zs[3]:
                bad.append((tag, e, g, w, n * 2 ** 32, zs))
                continue
            open(os.path.join(args.out, f"Gf2Seam{tag}_{e}.lean"), "w").write(
                lean(tag, n, hin0, e, mp, B, FL, BD))
            written += 1
    print(f"wrote {written} seam modules")
    if bad:
        print(f"BOUND FAILS ({len(bad)}):")
        for r in bad[:10]:
            print("   ", r)
