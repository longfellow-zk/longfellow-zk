import gen_comp, comp2
from gen_comp import insts, compose, detail, wordleaves, lname, bitpos
OUT = "/Users/abhi/Projects/longfellow-zk/formal/circuits/quadcert/Bridge/Sha256"
LET = "ABCDEFGH"
HDR = """/-
# Schedule steps {lo}-{hi}: the recurrence, over the deployed circuit

Generated by `tools/gen_comp.py`. Do not edit. The final composition of the schedule bridge:
`zval_S*` (the regrouping) and `allWrap4` (the field half) meet in `wrap_four_words`, and
`SHA256F.group_val_eq'` plus `SHA256.sigma0_bits`/`sigma1_bits` name the four `Nat`s.

`sched t` is exactly `SHA256.sha256_soundness`'s `hsched` hypothesis at step `t`, phrased over
`wordBits`, so the 48 steps chain: step `t` speaks about the same list step `t-15` produced.
-/

import quadcert.Bridge.Sha256.S2Sched{L}
import quadcert.Bridge.Sha256.S2Words
import quadcert.Bridge.Sha256.S2EdgesSched

set_option maxRecDepth 8000000
set_option maxHeartbeats 4000000

namespace Sha256Blk

open Quadcert Quadcert.Gen.Sha256Blk

variable {{F : Type}} [Field F]

"""
for n in range(8):
    chunk = insts[n*6:(n+1)*6]
    body = HDR.format(lo=chunk[0]['t'], hi=chunk[-1]['t'], L=LET[n])
    for d in chunk:
        body += compose(d) + "\n" + comp2.make(d, detail, wordleaves, lname, bitpos) + "\n" + comp2.final(d) + "\n"
    body += "end Sha256Blk\n"
    open(os.path.join(OUT, f"S2Comp{LET[n]}.lean"), "w").write(body)
    print(f"  S2Comp{LET[n]}.lean  t={chunk[0]['t']}..{chunk[-1]['t']}  {body.count(chr(10))} lines")
