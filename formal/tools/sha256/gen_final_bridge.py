def signed(c):
    v = consts[c]
    return v - P256 if v > P256 // 2 else v

# --- bit -> booleanity assertion ---------------------------------------------------------
bit2assert = {}
for (root, _, _) in asserts:
    k, v = nodes[root]
    if k == 'sum' and len(v) == 2:
        (k1, a1, b1), (k2, a2, b2) = v
        assert k1 == 0 and a1 == 0 and k2 == 2 and a2 == b2 == b1, (root, v)
        bit2assert[b1] = root

# --- the 8 final assertions ---------------------------------------------------------------
finals = []
for (root, _, _) in asserts:
    t, f = kind(root)
    if t == 'wrap' and len(f) == 3:
        z = [n for n in f if nodes[n][0] == 'sum' and len(nodes[n][1]) > 10][0]
        finals.append((root, z))
assert len(finals) == 8

def wordindex(name):
    m = re.match(r'h0_(\d+)_\d+$', name)
    return int(m.group(1)) if m else None

instances = []
for root, z in finals:
    terms = nodes[z][1]
    assert len(terms) == 96
    ts, mp = [], [0]
    csA, csB, ds, order = [], [], [], []
    idx_of_h0 = None
    for j, (k, a, b) in enumerate(terms):
        leaf = j + 1
        if a == 0:
            ts.append((k, 0, leaf)); bit = b
        elif b == 0:
            ts.append((k, leaf, 0)); bit = a
        else:
            raise SystemExit(f"non-linear term {(k,a,b)} in z={z}")
        mp.append(bit)
        w = signed(k)
        nk, nv = nodes[bit]
        name = layout.get(nv, "") if nk == 'input' else ""
        if w > 0:
            if name.startswith("h0_"):
                idx_of_h0 = wordindex(name); csA.append((w, leaf, bit))
            else:
                csB.append((w, leaf, bit))
        else:
            ds.append((-w, leaf, bit))
    mp.append(z)
    csA.sort(key=lambda t: t[0]); csB.sort(key=lambda t: t[0]); ds.sort(key=lambda t: t[0])
    assert len(csA) == 32 and len(csB) == 32 and len(ds) == 32, (root, len(csA), len(csB), len(ds))
    assert sum(w for w, _, _ in csA) == 2**32 - 1
    assert sum(w for w, _, _ in csB) == 2**32 - 1
    assert sum(w for w, _, _ in ds) == 2**32 - 1
    pairs = [(bit2assert[b], b) for _, _, b in csA + csB + ds]
    lpairs = [(bit2assert[x], x) for x in mp[1:97]]
    for ar, b in pairs:
        assert b < ar, (b, ar)
        assert ar < len(nodes)
    bname = layout.get(nodes[csB[0][2]][1], "?") if nodes[csB[0][2]][0] == 'input' else "?"
    dname = layout.get(nodes[ds[0][2]][1], "?") if nodes[ds[0][2]][0] == 'input' else "?"
    instances.append(dict(root=root, z=z, i=idx_of_h0, ts=ts, mp=mp,
                          csA=csA, csB=csB, ds=ds, pairs=pairs, lpairs=lpairs,
                          bname=bname, dname=dname))

instances.sort(key=lambda d: d['i'])
for d in instances:
    print(f"i={d['i']}  root={d['root']} z={d['z']}  addendB={d['bname']}  out={d['dname']}")

