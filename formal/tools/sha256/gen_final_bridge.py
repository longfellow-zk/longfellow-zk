def lst(xs):  return "[" + ", ".join(xs) + "]"

def const_haves(ks):
    out = []
    for k in sorted(ks):
        v = consts[k]; sv = signed(k)
        if sv > 0:
            out.append(f"  have c{k} : cnstw F {k} = (({sv} : Nat) : F) := cnstw_pos {k} {sv} (by rfl)")
        else:
            out.append(f"  have c{k} : cnstw F {k} = -(({-sv} : Nat) : F) := "
                       f"cnstw_neg {k} {-sv} (by rfl) (by norm_num)")
    return out

