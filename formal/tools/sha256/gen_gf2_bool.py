"""Emit all 6,656 GF(2^128) booleanity assertions as ONE edge list.

The artifact's only other assertion shape is the wrapping-sum product, so this module plus
`Gf2Wrap.lean` covers every assertion in the circuit.  Both coefficients of the booleanity node
are the unit constant (index 0) — in characteristic 2 the prime field's `-1` is `1` — so the cone
is `sum [(0, 0, x), (0, x, x)]`, one constant lighter than `Bridge/Sha256/S2Edges.lean`'s.

`assertOfB` and `bitOfB` are bisections over the edge index, not list lookups: measured on the
p256 bridge, list lookups abort at n = 4096.

Usage: SHA_ARTIFACT=Sha256Gf2 python3 gen_gf2_bool.py [--out DIR] [--chunk 512]
"""
import sys, os, argparse
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_gf2_wrap as G

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
BRIDGE = os.path.join(ROOT, "circuits", "quadcert", "Bridge", "Sha256Gf2")
NNODES = len(G.nodes)


def pairs():
    """(assertion node, bit node) for every booleanity assertion, in assertion order."""
    out = []
    for (root, _, _) in G.read_asserts():
        k, v = G.nodes[root]
        if k == 'sum' and len(v) == 2 and v[0][:2] == (0, 0) and v[1] == (0, v[0][2], v[0][2]):
            out.append((root, v[0][2]))
    return out


def bisect(vals, lo, hi):
    """`vals[lo:hi]` as a balanced if-tree on the edge index `e`."""
    if hi - lo == 1:
        return str(vals[lo])
    mid = (lo + hi) // 2
    return f"if e < {mid} then {bisect(vals, lo, mid)} else {bisect(vals, mid, hi)}"


HEAD = """import quadcert.Bridge.Sha256Gf2.Gf2Bool
import quadcert.Bridge.Sha256Gf2.Gf2Wrap
"""


def emit_map(ps):
    """The bisections and their range checks. One module, because the two 370 KB if-trees are the
    expensive part to elaborate and every chunk module needs them."""
    n = len(ps)
    out = [HEAD]
    A = out.append
    A("/-!")
    A(f"# The booleanity edge list's index maps ({n:,} edges)")
    A("")
    A("`assertOfB` and `bitOfB` are bisections over the edge index, not list lookups: measured on")
    A("the p256 bridge, list lookups abort at n = 4096. They live in their own module because")
    A("elaborating a 6,656-leaf if-tree is the expensive part, and every chunk module needs it.")
    A("")
    A("Generated by `tools/sha256/gen_gf2_bool.py`.")
    A("-/")
    A("")
    A("set_option maxRecDepth 8000000")
    A("set_option maxHeartbeats 0")
    A("")
    A("namespace Sha256Gf2")
    A("")
    A("open Quadcert Quadcert.Gen.Sha256Gf2")
    A("")
    A("def assertOfB : Nat → Nat := fun e =>")
    A("  (" + bisect([a for a, _ in ps], 0, n) + ")")
    A("")
    A("def bitOfB : Nat → Nat := fun e =>")
    A("  (" + bisect([b for _, b in ps], 0, n) + ")")
    A("")
    A("def mapOfB : Nat → Nat → Nat := fun e i =>")
    A("  if i < 1 then 0 else if i < 2 then bitOfB e else assertOfB e")
    A("")
    A("/-! Two flat `decide`s, not one nested over `range n × range 3`: the nested form aborts at")
    A("the memory cap even though the chunk checks, which evaluate `mapOfB` far more often, do")
    A("not. -/")
    A("")
    A(f"theorem bitOfB_lt : (List.range {n}).all (fun e => decide (bitOfB e < {NNODES})) = true := by")
    A("  decide +kernel")
    A("")
    A(f"theorem assertOfB_lt : (List.range {n}).all (fun e => decide (assertOfB e < {NNODES}))")
    A("    = true := by")
    A("  decide +kernel")
    A("")
    A("/-- Every mapped node is real. -/")
    A(f"theorem mapOfB_lt : ∀ e, e < {n} → ∀ i, i < tnBool.length → mapOfB e i < raw.nodes.length := by")
    A(f"  have hb : ∀ e, e < {n} → bitOfB e < {NNODES} := by")
    A("    have h := bitOfB_lt")
    A("    simp only [List.all_eq_true, List.mem_range, decide_eq_true_eq] at h")
    A("    exact h")
    A(f"  have ha : ∀ e, e < {n} → assertOfB e < {NNODES} := by")
    A("    have h := assertOfB_lt")
    A("    simp only [List.all_eq_true, List.mem_range, decide_eq_true_eq] at h")
    A("    exact h")
    A("  intro e he i hi")
    A("  rw [nodes_len]")
    A("  unfold mapOfB")
    A("  by_cases h1 : i < 1")
    A("  · simp only [h1, if_pos]; norm_num")
    A("  · by_cases h2 : i < 2")
    A("    · simp only [h1, h2, if_pos, if_false]")
    A("      exact hb e he")
    A("    · simp only [h1, h2, if_false]")
    A("      exact ha e he")
    A("")
    A("end Sha256Gf2")
    return "\n".join(out) + "\n"


def emit_chunk(k, lo, ln):
    """One slice of the edge list. One heavy `decide +kernel` per module: Lean elaborates a
    module's declarations in parallel, so thirteen of these in one file multiply the peak by
    thirteen and abort — measured, at 16 GB."""
    return f"""import quadcert.Bridge.Sha256Gf2.Gf2BoolMap

/-! Booleanity edges `{lo} … {lo + ln - 1}`, matched against `tnBool`. -/

set_option maxRecDepth 8000000
set_option maxHeartbeats 0

namespace Sha256Gf2

open Quadcert Quadcert.Gen.Sha256Gf2

theorem ec{k} : edgesMatchAt nodeFn tnBool mapOfB {lo} {ln} = true := by decide +kernel

end Sha256Gf2
"""


def emit_top(ps, cs):
    n = len(ps)
    cslist = "[" + ", ".join(f"({lo}, {ln})" for lo, ln in cs) + "]"
    out = []
    A = out.append
    for k in range(len(cs)):
        A(f"import quadcert.Bridge.Sha256Gf2.Gf2BoolE{k}")
    A("")
    A("/-!")
    A(f"# All {n:,} `is_boolean` assertions as one edge list")
    A("")
    A(f"The {len(cs)} slices are composed by `edgesMatch_of_chunks`; `allBoolBits` then concludes")
    A("booleanity for every bit in the circuit from that one structural check plus `tmpl_isBool`.")
    A("")
    A("Together with `Gf2Wrap.lean`'s 184 wrapping-sum cones this is *every* assertion the")
    A("artifact makes: 6,656 + 184 = 6,840.")
    A("")
    A("There is no per-assertion module, no per-assertion lemma and no per-assertion algebra.")
    A("-/")
    A("")
    A("set_option maxRecDepth 8000000")
    A("set_option maxHeartbeats 0")
    A("")
    A("namespace Sha256Gf2")
    A("")
    A("open Quadcert Quadcert.Gen.Sha256Gf2")
    A("")
    A(f"theorem allBoolEdges : edgesMatch nodeFn tnBool mapOfB {n} = true := by")
    A("  -- hoisted: inside `refine` this elaborates against metavariables and blows the interpreter")
    A(f"  have ht : tiles {cslist} 0 {n} = true := by decide +kernel")
    A(f"  refine edgesMatch_of_chunks nodeFn tnBool mapOfB {cslist} {n} ht ?_")
    A("  intro c hc")
    A("  simp only [List.mem_cons, List.not_mem_nil, or_false] at hc")
    A("  rcases hc with " + "|".join(["rfl"] * len(cs)))
    for k, (lo, ln) in enumerate(cs):
        A(f"  · show edgesMatchAt nodeFn tnBool mapOfB {lo} {ln} = true")
        A(f"    exact ec{k}")
    A("")
    A("variable {F : Type} [Field F] [CharP F 2]")
    A("")
    A("/-- **Booleanity of every bit in the circuit, from one edge list.** All the bits every")
    A("    injection cone reads, from one structural `decide` and one template lemma. -/")
    A("theorem allBoolBits (α : F) (inputs : Nat → F) (hin0 : inputs 0 = 1)")
    A(f"    (hz : ∀ e, e < {n} → interpDag (raw.toDag (consts α)) inputs (assertOfB e) = 0) :")
    A(f"    ∀ e, e < {n} →")
    A("      interpDag (raw.toDag (consts α)) inputs (bitOfB e) = 0")
    A("        ∨ interpDag (raw.toDag (consts α)) inputs (bitOfB e) = 1 := by")
    A("  intro e he")
    A(f"  have htr := edges_transfer raw (consts α) inputs nodeFn nodefn_ok tnBool mapOfB {n}")
    A("    allBoolEdges mapOfB_lt e he")
    A("  have hone : (fun h => interpDag (raw.toDag (consts α)) inputs (mapOfB e h)) 0 = 1 := by")
    A("    show interpDag (raw.toDag (consts α)) inputs 0 = 1")
    A("    exact node0 α inputs hin0")
    A("  have hroot : interpDag (tmplDag (consts α) tnBool)")
    A("      (fun h => interpDag (raw.toDag (consts α)) inputs (mapOfB e h)) 2 = 0 := by")
    A("    rw [← htr 2 (by decide)]")
    A("    show interpDag (raw.toDag (consts α)) inputs (assertOfB e) = 0")
    A("    exact hz e he")
    A("  have hb := tmpl_isBool (consts α)")
    A("    (fun h => interpDag (raw.toDag (consts α)) inputs (mapOfB e h)) (consts_one α) hone hroot")
    A("  show interpDag (raw.toDag (consts α)) inputs (bitOfB e) = 0")
    A("    ∨ interpDag (raw.toDag (consts α)) inputs (bitOfB e) = 1")
    A("  exact hb")
    A("")
    A("end Sha256Gf2")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=BRIDGE)
    ap.add_argument("--chunk", type=int, default=512)
    args = ap.parse_args()
    ps = pairs()
    assert len({b for _, b in ps}) == len(ps), "bit nodes must be distinct"
    assert all(b < a for a, b in ps), "bit node must precede its assertion"
    assert all(G.nodes[b][0] == 'input' for _, b in ps), "bit nodes must be inputs"
    n = len(ps)
    cs = [(lo, min(args.chunk, n - lo)) for lo in range(0, n, args.chunk)]
    open(os.path.join(args.out, "Gf2BoolMap.lean"), "w").write(emit_map(ps))
    for k, (lo, ln) in enumerate(cs):
        open(os.path.join(args.out, f"Gf2BoolE{k}.lean"), "w").write(emit_chunk(k, lo, ln))
    open(os.path.join(args.out, "Gf2BoolEdges.lean"), "w").write(emit_top(ps, cs))
    print(f"wrote Gf2BoolMap + {len(cs)} chunk modules + Gf2BoolEdges: "
          f"{n} edges, bit-node sum {sum(b for _, b in ps)}")
