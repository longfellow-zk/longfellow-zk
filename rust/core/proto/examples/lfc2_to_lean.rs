//! Emit packed, kernel-checkable Lean modules for an LFC2 artifact.
//!
//! The committed payload is the LFC2 encoding itself, so nothing is re-serialized into a second
//! format on the way to the page-Merkle root.
//!
//! Usage:
//! `cargo run -p core-proto --example lfc2_to_lean -- FIELD INPUT OUTPUT_DIR NAME`
//! where `FIELD` is `p256` or `gf2_128` and `NAME` is a valid Lean identifier.

use std::{env, fmt::Write as _, fs, path::Path};

use compile_algebra::{gf2_128::Gf2_128Field, p256::P256Field};
use core_proto::{
    circuit::Circuit,
    commitment::{formal_page_leaf_hash, FormalCircuitCommitment, FORMAL_PAGE_SIZE},
    reader::CircuitReader,
    writer::{
        CircuitWriter,
    },
    FieldID, Layer, SerializableField,
};

const DEFAULT_TERM_CHUNK_SIZE: usize = 1024;

fn main() -> Result<(), String> {
    let args: Vec<String> = env::args().collect();
    if !(5..=6).contains(&args.len()) {
        return Err(format!(
            "usage: {} FIELD INPUT OUTPUT_DIR NAME [TERM_CHUNK_SIZE]",
            args.first().map_or("lfc2_to_lean", String::as_str)
        ));
    }
    let term_chunk_size = args
        .get(5)
        .map(|value| value.parse::<usize>())
        .transpose()
        .map_err(|error| format!("invalid TERM_CHUNK_SIZE: {error}"))?
        .unwrap_or(DEFAULT_TERM_CHUNK_SIZE);
    if term_chunk_size == 0 {
        return Err("TERM_CHUNK_SIZE must be nonzero".to_string());
    }
    let input = fs::read(&args[2]).map_err(|error| format!("read {}: {error}", args[2]))?;
    let output = Path::new(&args[3]);
    fs::create_dir_all(output).map_err(|error| format!("create {}: {error}", output.display()))?;

    match args[1].as_str() {
        "p256" => convert(
            &P256Field::new(),
            FieldID::P256,
            &input,
            output,
            &args[4],
            term_chunk_size,
        ),
        "gf2_128" => convert(
            &Gf2_128Field::new(),
            FieldID::Gf2_128,
            &input,
            output,
            &args[4],
            term_chunk_size,
        ),
        field => Err(format!(
            "unsupported field {field:?}; expected p256 or gf2_128"
        )),
    }
}

fn convert<F: SerializableField>(
    field: &F,
    field_id: FieldID,
    lfc2: &[u8],
    output: &Path,
    name: &str,
    term_chunk_size: usize,
) -> Result<(), String> {
    let reader = CircuitReader::new(field, field_id);
    let (circuit, trailing) = reader.from_bytes_lfc2(lfc2, true)?;
    if !trailing.is_empty() {
        return Err(format!("LFC2 input has {} trailing bytes", trailing.len()));
    }
    let writer = CircuitWriter::new(field, field_id);
    let bytes = writer.to_bytes_lfc2(&circuit);
    let commitment = FormalCircuitCommitment::new(&bytes);
    let pages: Vec<&[u8]> = bytes.chunks(FORMAL_PAGE_SIZE).collect();

    for (index, page) in pages.iter().enumerate() {
        let packed = packed_hex(page);
        let packed_module = format!(
            "-- Generated by `lfc2_to_lean`; do not edit.\n\
             namespace Quadcert.Gen.{name}\n\
             def packedPage_{index} : Nat := 0x{packed}\n\
             end Quadcert.Gen.{name}\n"
        );
        write_module(output, &format!("Gen/{name}/{name}Packed{index}.lean"), &packed_module)?;

        // The same page as a byte list, plus the two checks that make it advice rather than
        // something trusted. `packBytes` is the little-endian packing the commitment uses, so
        // `pageBytes_ok` says this list *is* the committed page; `bytesOk` bounds every entry.
        //
        // Both are one `rfl`. Measured on a full 4,096-byte page: 3.3 s and 511 MB, because the
        // kernel evaluates the fold strictly instead of retaining an intermediate per byte —
        // which is exactly the asymmetry that makes reading from bytes cheap and reading from
        // the packed numeral expensive (175 s / 9.5 GB for one 1,024-delta chunk).
        // Zero-padded to a full page. `packBytes` is little-endian, so trailing zeros do not
        // change the value — `pageBytes_ok` still holds — but every page now has length
        // `pageSize`, which is what `PagesRefine` needs and what the final short page would
        // otherwise fail.
        let mut padded = page.to_vec();
        padded.resize(FORMAL_PAGE_SIZE, 0);
        let byte_list = padded.iter().map(u8::to_string).collect::<Vec<_>>().join(", ");
        let bytes_module = format!(
            "-- Generated by `lfc2_to_lean`; do not edit.\n\
             import quadcert.Core.Lfc2Bytes\n\
             import quadcert.Gen.{name}.{name}Packed{index}\n\
             set_option maxRecDepth 4000000\n\
             set_option maxHeartbeats 0\n\
             namespace Quadcert.Gen.{name}\n\
             open Quadcert.Lfc2\n\
             def pageBytes_{index} : List Nat := [{byte_list}]\n\
             theorem pageBytes_ok_{index} :\n  \
               packBytes pageBytes_{index} = packedPage_{index} := by rfl\n\
             theorem pageBytes_range_{index} :\n  \
               bytesOk pageBytes_{index} = true := by rfl\n\
             end Quadcert.Gen.{name}\n"
        );
        write_module(output, &format!("Gen/{name}/{name}Bytes{index}.lean"), &bytes_module)?;

        let leaf = formal_page_leaf_hash(bytes.len() as u64, index as u64, page);
        let leaf_module = format!(
            "-- Generated by `lfc2_to_lean`; do not edit.\n\
             import quadcert.Core.CircuitCommitment\n\
             import quadcert.Gen.{name}.{name}Packed{index}\n\
             set_option maxHeartbeats 0\n\
             set_option maxRecDepth 1000000\n\
             namespace Quadcert.Gen.{name}\n\
             def leaf_{index} : QuadCert.Sha256.Digest := {}\n\
             theorem leaf_ok_{index} :\n\
               QuadCert.CircuitCommitment.packedLeafHash {} {index} {} packedPage_{index}\n\
                 = leaf_{index} := by decide +kernel\n\
             end Quadcert.Gen.{name}\n",
            lean_bytes(&leaf),
            bytes.len(),
            page.len(),
        );
        write_module(
            output,
            &format!("Gen/{name}/{name}Commitment{index}.lean"),
            &leaf_module,
        )?;
    }

    let packed_imports = (0..pages.len())
        .map(|index| format!("import quadcert.Gen.{name}.{name}Packed{index}\n"))
        .collect::<String>();
    let packed_names = (0..pages.len())
        .map(|index| format!("packedPage_{index}"))
        .collect::<Vec<_>>()
        .join(", ");
    let packed_index = format!(
        "-- Generated by `lfc2_to_lean`; do not edit.\n\
         import quadcert.Core.Lfc2\n\
         {packed_imports}\
         namespace Quadcert.Gen.{name}\n\
         def packedInput : Quadcert.Lfc2.PackedBytes :=\n\
           {{ byteLength := {}, pages := [{packed_names}] }}\n\
         end Quadcert.Gen.{name}\n",
        bytes.len()
    );
    write_module(output, &format!("Gen/{name}/{name}Packed.lean"), &packed_index)?;

    let byte_imports = (0..pages.len())
        .map(|index| format!("import quadcert.Gen.{name}.{name}Bytes{index}\n"))
        .collect::<String>();
    let byte_names = (0..pages.len())
        .map(|index| format!("pageBytes_{index}"))
        .collect::<Vec<_>>()
        .join(", ");
    let byte_index = format!(
        "-- Generated by `lfc2_to_lean`; do not edit.\n\
         import quadcert.Core.Lfc2Bytes\n\
         import quadcert.Gen.{name}.{name}Packed\n\
         {byte_imports}\
         set_option maxRecDepth 4000000\nset_option maxHeartbeats 0\n\
         namespace Quadcert.Gen.{name}\n\
         open Quadcert.Lfc2\n\
         /-- The committed pages as byte lists. Every entry is tied to the corresponding\n\
             `packedPage_i` by `pageBytes_ok_i`, so this is checked advice: the readers may use\n\
             it, and the Merkle leaf hashes still go through the packed numerals. -/\n\
         def inputBytes : List (List Nat) := [{byte_names}]\n\
         /-- Each byte page really is the committed page. Right-nested because `PagesRefine`\n\
             recurses on the two lists together. -/\n\
         theorem pagesRefine : PagesRefine packedInput.pages inputBytes :=\n  \
           {pages_refine}\n\
         end Quadcert.Gen.{name}\n",
        pages_refine = {
            let mut acc = "trivial".to_string();
            for index in (0..pages.len()).rev() {
                acc = format!(
                    "⟨pageBytes_ok_{index}, pageBytes_range_{index}, by decide, {acc}⟩"
                );
            }
            acc
        }
    );
    write_module(output, &format!("Gen/{name}/{name}Bytes.lean"), &byte_index)?;

    let commitment_imports = (0..pages.len())
        .map(|index| format!("import quadcert.Gen.{name}.{name}Commitment{index}\n"))
        .collect::<String>();
    let leaf_names = (0..pages.len())
        .map(|index| format!("leaf_{index}"))
        .collect::<Vec<_>>()
        .join(", ");
    let leaf_checks = (0..pages.len())
        .map(|index| format!("leaf_ok_{index}"))
        .collect::<Vec<_>>()
        .join(", ");
    let committed_leaves = pages
        .iter()
        .enumerate()
        .map(|(index, page)| {
            format!(
                "QuadCert.CircuitCommitment.packedLeafHash {} {index} {} packedPage_{index}",
                bytes.len(),
                page.len()
            )
        })
        .collect::<Vec<_>>()
        .join(", ");
    let root_module = format!(
        "-- Generated by `lfc2_to_lean`; do not edit.\n\
         {commitment_imports}\
         namespace Quadcert.Gen.{name}\n\
         def formalRoot : QuadCert.Sha256.Digest := {}\n\
         theorem root_from_leaves :\n  \
         QuadCert.CircuitCommitment.rootFromLeaves {} [{leaf_names}] = formalRoot := by decide +kernel\n\
         theorem committed_root :\n  \
         QuadCert.CircuitCommitment.rootFromLeaves {} [{committed_leaves}] = formalRoot := by\n  \
         rw [{leaf_checks}]\n  \
         exact root_from_leaves\n\
         end Quadcert.Gen.{name}\n",
        lean_bytes(&commitment.root),
        bytes.len(),
        bytes.len(),
    );
    write_module(output, &format!("Gen/{name}/{name}Commitment.lean"), &root_module)?;

    emit_verified_decode_modules(
        field,
        field_id,
        &circuit,
        &bytes,
        output,
        name,
        term_chunk_size,
    )?;

    fs::write(output.join(format!("{name}.lfc3")), &bytes)
        .map_err(|error| format!("write LFC2: {error}"))?;
    println!(
        "{}: LFC2={} committed={} pages={} root={} ninput={} npublic={} noutput={} constants={} layers={} terms={:?}",
        name,
        lfc2.len(),
        bytes.len(),
        pages.len(),
        hex(&commitment.root),
        circuit.raw.ninput,
        circuit.raw.npublic_input,
        circuit.raw.noutput,
        circuit.raw.constants.len(),
        circuit.raw.layers.len(),
        circuit.raw.layers.iter().map(Layer::num_terms).collect::<Vec<_>>()
    );
    println!(
        "{}: deltas={:?} segment_symbols={:?} tokens={:?}",
        name,
        circuit
            .raw
            .layers
            .iter()
            .map(|layer| layer.deltas().len())
            .collect::<Vec<_>>(),
        circuit
            .raw
            .layers
            .iter()
            .map(|layer| layer.delta_segments().iter().map(Vec::len).sum::<usize>())
            .collect::<Vec<_>>(),
        circuit
            .raw
            .layers
            .iter()
            .map(|layer| layer.delta_tokens().len())
            .collect::<Vec<_>>()
    );
    Ok(())
}

#[derive(Clone, Debug, Default, PartialEq, Eq)]
struct ExpansionCheckpoint {
    /// How many tokens/roots have been popped; the Lean cursor's `outer` is the rest.
    outer_drop: usize,
    /// Remaining symbols of the open phrase (bounded by `maxPhraseLength`).
    /// Remaining delta indices of the open segment (bounded by the segment width).
    segment: Vec<u32>,
    /// Where the delta zipper sits; the Lean cursor rebuilds it by take/reverse/drop.
    delta_pos: usize,
    g: u32,
    h0: u32,
    h1: u32,
    emitted: usize,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
struct ExpandedTerm {
    g: u32,
    h0: u32,
    h1: u32,
    k_index: u32,
}

fn emit_verified_decode_modules<F: SerializableField>(
    field: &F,
    field_id: FieldID,
    circuit: &Circuit<F>,
    lfc3: &[u8],
    output: &Path,
    name: &str,
    term_chunk_size: usize,
) -> Result<(), String> {
    let layer_offsets = lfc2_layer_offsets(lfc3, field.serialized_size_bytes())?;
    if layer_offsets.len() != circuit.raw.layers.len() + 1 {
        return Err("LFC2 layer offset count disagrees with circuit".to_string());
    }
    let cursor_defs = layer_offsets
        .iter()
        .enumerate()
        .map(|(index, &offset)| {
            format!(
                "def parseCursor_{index} : Cursor := {}\n\
                 def bparseCursor_{index} : BCursor := \
                 bcursorAt packedInput.byteLength inputBytes {offset}\n\
                 theorem hrefParse_{index} : \
                 Refines parseCursor_{index} bparseCursor_{index} :=\n  \
                 cursorAt_refines packedInput inputBytes {offset} pagesRefine (by decide)\n",
                lean_parse_cursor(lfc3, offset)
            )
        })
        .collect::<String>();
    let cursors_module = format!(
        "-- Generated by `lfc2_to_lean`; do not edit.\n\
         import quadcert.Gen.{name}.{name}Packed\n\
         import quadcert.Gen.{name}.{name}Bytes\n\
         set_option maxRecDepth 4000000\nset_option maxHeartbeats 0\n\
         namespace Quadcert.Gen.{name}\n\
         open Quadcert.Lfc2\n\n\
         {cursor_defs}\
         end Quadcert.Gen.{name}\n"
    );
    write_module(output, &format!("Gen/{name}/{name}ParseCursors.lean"), &cursors_module)?;

    let constants = circuit
        .raw
        .constants
        .iter()
        .map(|value| format!("0x{}", packed_hex(&field.to_bytes(value))))
        .collect::<Vec<_>>()
        .join(", ");
    let field_name = lean_field_name(field_id)?;
    let header_module = format!(
        "-- Generated by `lfc2_to_lean`; do not edit.\n\
         import quadcert.Gen.{name}.{name}Packed\n\
         import quadcert.Gen.{name}.{name}ParseCursors\n\
         set_option maxRecDepth 1000000\n\
         set_option maxHeartbeats 0\n\
         namespace Quadcert.Gen.{name}\n\
         open Quadcert.Lfc2\n\n\
         def header : CompressedHeader := {{ fieldId := {}, ninput := {}, npublicInput := {}, noutput := {}, logv := {}, subfieldBoundary := {}, constants := #[{}], layerCount := {} }}\n\n\
         theorem parse_header_ok : parseHeader {field_name} packedInput = .ok (header, parseCursor_0) := by rfl\n\
         end Quadcert.Gen.{name}\n",
        field_id as u32,
        circuit.raw.ninput,
        circuit.raw.npublic_input,
        circuit.raw.noutput,
        circuit.raw.logv,
        circuit.raw.subfield_boundary,
        constants,
        circuit.raw.layers.len(),
    );
    write_module(output, &format!("Gen/{name}/{name}Header.lean"), &header_module)?;

    let mut prior_terms = 0usize;

    for (layer_index, layer) in circuit.raw.layers.iter().enumerate() {
        // Width of the block this layer writes into, bounding every term's `g`.  Matches
        // `eval.rs`, which passes exactly this as `noutput` to `eval_layer`.
        let g_bound = if layer_index == 0 {
            circuit.raw.noutput
        } else {
            circuit.raw.layers[layer_index - 1].nw()
        };
        let st = lfc2_layer_stages(lfc3, layer_offsets[layer_index], term_chunk_size)?;

        // Stage cursors for this layer.  Emitted once, imported by every stage module.
        let mut cursors = String::new();
        let mut cur_name = |tag: &str| format!("cur_{layer_index}_{tag}");
        writeln!(
            cursors,
            "def {} : Cursor := {}",
            cur_name("prefix"),
            lean_parse_cursor(lfc3, st.after_prefix)
        )
        .expect("write String");
        for (j, off) in st.delta_bounds.iter().enumerate() {
            writeln!(
                cursors,
                "def {} : Cursor := {}",
                cur_name(&format!("d{j}")),
                lean_parse_cursor(lfc3, *off)
            )
            .expect("write String");
        }
        writeln!(
            cursors,
            "def {} : Cursor := {}",
            cur_name("segcount"),
            lean_parse_cursor(lfc3, st.after_seg_count)
        )
        .expect("write String");
        for (j, off) in st.segment_bounds.iter().enumerate() {
            writeln!(
                cursors,
                "def {} : Cursor := {}",
                cur_name(&format!("s{j}")),
                lean_parse_cursor(lfc3, *off)
            )
            .expect("write String");
        }
        // The same offsets as byte cursors, plus the refinement witness for each. `by decide`
        // discharges `offset / pageSize < pages.length`, which is a comparison of two numerals.
        let mut bcursors = String::new();
        {
            let mut emit_b = |tag: String, off: usize| {
                writeln!(
                    bcursors,
                    "def b{0} : BCursor := bcursorAt packedInput.byteLength inputBytes {1}\n\
                     theorem href_{0} : Refines {0} b{0} :=\n  \
                       cursorAt_refines packedInput inputBytes {1} pagesRefine (by decide)",
                    cur_name(&tag),
                    off
                )
                .expect("write String");
            };
            emit_b("prefix".to_string(), st.after_prefix);
            for (j, off) in st.delta_bounds.iter().enumerate() {
                emit_b(format!("d{j}"), *off);
            }
            emit_b("segcount".to_string(), st.after_seg_count);
            for (j, off) in st.segment_bounds.iter().enumerate() {
                emit_b(format!("s{j}"), *off);
            }
        }
        write_module(
            output,
            &format!("Gen/{name}/{name}LayerCursors{layer_index}.lean"),
            &format!(
                "-- Generated by `lfc2_to_lean`; do not edit.\n\
                 import quadcert.Gen.{name}.{name}Packed\n\
                 import quadcert.Gen.{name}.{name}Bytes\n\
                 set_option maxRecDepth 4000000\nset_option maxHeartbeats 0\n\
                 namespace Quadcert.Gen.{name}\nopen Quadcert.Lfc2\n\n{cursors}\n{bcursors}\
                 end Quadcert.Gen.{name}\n"
            ),
        )?;

        // Delta chunks: each module holds only its own slice of the delta table.
        let deltas = layer.deltas();
        let ndchunks = st.delta_bounds.len() - 1;
        for j in 0..ndchunks {
            let lo = j * term_chunk_size;
            let hi = ((j + 1) * term_chunk_size).min(deltas.len());
            let items = deltas[lo..hi]
                .iter()
                .map(|d| format!("⟨{}, {}, {}, {}⟩", d.g, d.h[0], d.h[1], d.k_index))
                .collect::<Vec<_>>()
                .join(", ");
            write_module(
                output,
                &format!("Gen/{name}/{name}Deltas{layer_index}_{j}.lean"),
                &format!(
                    "-- Generated by `lfc2_to_lean`; do not edit.\n\
                     import quadcert.Gen.{name}.{name}LayerCursors{layer_index}\n\
                     set_option maxRecDepth 1000000\nset_option maxHeartbeats 0\n\
                     namespace Quadcert.Gen.{name}\nopen Quadcert.Lfc2\n\n\
                     def deltas_{layer_index}_{j} : List Delta := [{items}]\n\n\
                     /-- Proved with the byte reader and transferred. The packed reader forces\n\
                         one bignum per byte when the deltas meet their literals, which is the\n\
                         18 GB abort on SHA-256's largest layer; the byte reader pops a `cons`. -/\n\
                     theorem deltas_ok_{layer_index}_{j} :\n  \
                     readDeltasChunk {0} {1} {2} = .ok (deltas_{layer_index}_{j}, {3}) :=\n  \
                     readDeltasChunk_transfer {0} {1} href_{2} href_{3}\n    \
                       (by rfl : readDeltasChunkB {0} {1} b{2} \
                     = .ok (deltas_{layer_index}_{j}, b{3}))\n\
                     end Quadcert.Gen.{name}\n",
                    circuit.raw.constants.len(),
                    hi - lo,
                    cur_name(&format!("d{j}")),
                    cur_name(&format!("d{}", j + 1)),
                ),
            )?;
        }
        let delta_names = (0..ndchunks)
            .map(|j| format!("deltas_{layer_index}_{j}"))
            .collect::<Vec<_>>()
            .join(" ++ ");
        let mut dcompose = String::new();
        if ndchunks <= 1 {
            writeln!(dcompose, "  simpa [allDeltas_{layer_index}] using deltas_ok_{layer_index}_0")
                .expect("write String");
        } else {
            writeln!(dcompose, "  have h_0 := deltas_ok_{layer_index}_0").expect("write String");
            for j in 1..ndchunks {
                writeln!(
                    dcompose,
                    "  have h_{j} := readDeltasChunk_compose {} h_{} deltas_ok_{layer_index}_{j}",
                    circuit.raw.constants.len(),
                    j - 1
                )
                .expect("write String");
            }
            writeln!(
                dcompose,
                "  simpa [allDeltas_{layer_index}, Nat.reduceAdd, List.append_assoc] using h_{}",
                ndchunks - 1
            )
            .expect("write String");
        }
        write_module(
            output,
            &format!("Gen/{name}/{name}DeltasAll{layer_index}.lean"),
            &format!(
                "-- Generated by `lfc2_to_lean`; do not edit.\n{}\
                 set_option maxRecDepth 1000000\nset_option maxHeartbeats 0\n\
                 namespace Quadcert.Gen.{name}\nopen Quadcert.Lfc2\n\n\
                 def allDeltas_{layer_index} : List Delta := {delta_names}\n\n\
                 theorem deltas_all_ok_{layer_index} :\n  \
                 readDeltasChunk {} {} {} = .ok (allDeltas_{layer_index}, {}) := by\n{dcompose}\
                 end Quadcert.Gen.{name}\n",
                (0..ndchunks)
                    .map(|j| format!("import quadcert.Gen.{name}.{name}Deltas{layer_index}_{j}\n"))
                    .collect::<String>(),
                circuit.raw.constants.len(),
                st.delta_count,
                cur_name("d0"),
                cur_name(&format!("d{ndchunks}")),
            ),
        )?;

        // The delta tree: advice, checked against the parsed list by `deltas_ok_{layer_index}`.
        let dvals: Vec<(u32, u32, u32, u32)> = deltas
            .iter()
            .map(|d| (d.g, d.h[0], d.h[1], d.k_index))
            .collect();
        write_module(
            output,
            &format!("Gen/{name}/{name}DeltaTree{layer_index}.lean"),
            &format!(
                "-- Generated by `lfc2_to_lean`; do not edit.\n\
                 import quadcert.Gen.{name}.{name}DeltasAll{layer_index}\n\
                 set_option maxRecDepth 1000000\nset_option maxHeartbeats 0\n\
                 namespace Quadcert.Gen.{name}\nopen Quadcert.Lfc2\n\n\
                 def deltaTree_{layer_index} : PTree Delta := {}\n\
                 end Quadcert.Gen.{name}\n",
                lean_delta_tree(&dvals, 0, dvals.len())
            ),
        )?;

        // Segment chunks, same shape; the symbol budget threads through the composition.
        let segments = layer.delta_segments();
        let nschunks = st.segment_bounds.len() - 1;
        let mut symbols_before = vec![0usize; nschunks + 1];
        for j in 0..nschunks {
            let lo = j * term_chunk_size;
            let hi = ((j + 1) * term_chunk_size).min(segments.len());
            symbols_before[j + 1] =
                symbols_before[j] + segments[lo..hi].iter().map(Vec::len).sum::<usize>();
        }
        for j in 0..nschunks {
            let lo = j * term_chunk_size;
            let hi = ((j + 1) * term_chunk_size).min(segments.len());
            let items = segments[lo..hi]
                .iter()
                .map(|seg| format!("Array.mk [{}]", seg.iter().map(u32::to_string).collect::<Vec<_>>().join(", ")))
                .collect::<Vec<_>>()
                .join(", ");
            write_module(
                output,
                &format!("Gen/{name}/{name}Segments{layer_index}_{j}.lean"),
                &format!(
                    "-- Generated by `lfc2_to_lean`; do not edit.\n\
                     import quadcert.Gen.{name}.{name}LayerCursors{layer_index}\n\
                     set_option maxRecDepth 1000000\nset_option maxHeartbeats 0\n\
                     namespace Quadcert.Gen.{name}\nopen Quadcert.Lfc2\n\n\
                     def segments_{layer_index}_{j} : List (Array Nat) := [{items}]\n\n\
                     /-- Proved with the byte reader and transferred; see `deltas_ok`. -/\n\
                     theorem segments_ok_{layer_index}_{j}_fast :\n  \
                     readSegmentsChunkB {0} {1} {2} b{3} \
                     = .ok (segments_{layer_index}_{j}, {4}, b{5}) := by rfl\n\
                     theorem segments_ok_{layer_index}_{j} :\n  \
                     readSegmentsChunk {0} {1} {2} {3} = .ok (segments_{layer_index}_{j}, {4}, {5}) :=\n  \
                     readSegmentsChunk_transfer {0} {1} {2} href_{3} href_{5} \
                     segments_ok_{layer_index}_{j}_fast\n\
                     end Quadcert.Gen.{name}\n",
                    st.delta_count,
                    hi - lo,
                    symbols_before[j],
                    cur_name(&format!("s{j}")),
                    symbols_before[j + 1],
                    cur_name(&format!("s{}", j + 1)),
                ),
            )?;
        }
        let segment_names = (0..nschunks)
            .map(|j| format!("segments_{layer_index}_{j}"))
            .collect::<Vec<_>>()
            .join(" ++ ");
        let mut scompose = String::new();
        if nschunks <= 1 {
            writeln!(scompose, "  simpa [allSegments_{layer_index}] using segments_ok_{layer_index}_0")
                .expect("write String");
        } else {
            writeln!(scompose, "  have h_0 := segments_ok_{layer_index}_0").expect("write String");
            for j in 1..nschunks {
                writeln!(
                    scompose,
                    "  have h_{j} := readSegmentsChunk_compose {} h_{} segments_ok_{layer_index}_{j}",
                    st.delta_count,
                    j - 1
                )
                .expect("write String");
            }
            writeln!(
                scompose,
                "  simpa [allSegments_{layer_index}, Nat.reduceAdd, List.append_assoc] using h_{}",
                nschunks - 1
            )
            .expect("write String");
        }
        write_module(
            output,
            &format!("Gen/{name}/{name}SegmentsAll{layer_index}.lean"),
            &format!(
                "-- Generated by `lfc2_to_lean`; do not edit.\n{}\
                 set_option maxRecDepth 1000000\nset_option maxHeartbeats 0\n\
                 namespace Quadcert.Gen.{name}\nopen Quadcert.Lfc2\n\n\
                 def allSegments_{layer_index} : List (Array Nat) := {segment_names}\n\n\
                 /-- Segment lengths, so the token stage never walks the dictionary. -/\n\
                 def segLens_{layer_index} : Array Nat := Array.mk [{seg_lens}]\n\n\
                 theorem seg_lens_ok_{layer_index} :\n  \
                 segmentLengths (Array.mk allSegments_{layer_index}) = segLens_{layer_index} := by rfl\n\n\
                 theorem segments_all_ok_{layer_index} :\n  \
                 readSegmentsChunk {} {} 0 {} = .ok (allSegments_{layer_index}, {}, {}) := by\n{scompose}\
                 end Quadcert.Gen.{name}\n",
                (0..nschunks)
                    .map(|j| format!("import quadcert.Gen.{name}.{name}Segments{layer_index}_{j}\n"))
                    .collect::<String>(),
                st.delta_count,
                st.segment_count,
                cur_name("s0"),
                symbols_before[nschunks],
                cur_name(&format!("s{nschunks}")),
                seg_lens = segments.iter().map(|s| s.len().to_string()).collect::<Vec<_>>().join(", "),
            ),
        )?;

        // The layer, assembled from the stages.  Note the deltas and segments are *referenced*,
        // never re-listed, so this module stays small however large the table is.
        let layer_module = format!(
            "-- Generated by `lfc2_to_lean`; do not edit.\n\
             import quadcert.Gen.{name}.{name}DeltaTree{layer_index}\n\
             import quadcert.Gen.{name}.{name}SegmentsAll{layer_index}\n\
             import quadcert.Gen.{name}.{name}ParseCursors\n\
             set_option maxRecDepth 1000000\n\
             set_option maxHeartbeats 0\n\
             namespace Quadcert.Gen.{name}\n\
             open Quadcert Quadcert.Lfc2\n\n\
             /-- Advice for the token stage's two lookup tables; `treeOk` validates each. -/\n\
             def segLensTree_{layer_index} : PTree Nat := {seg_lens_tree}\n\
             def compressedLayer_{layer_index} : CompressedLayer :=\n\
             {{ logw := {}, nw := {},\n  deltas := Array.mk allDeltas_{layer_index},\n  \
             segments := Array.mk allSegments_{layer_index},\n  tokens := {},\n  \
             tokenCount := {}, termCount := {} }}\n\n\
             /-- The tree is advice; this ties it to the list the parser produced. -/\n\
             theorem deltas_ok_{layer_index} :\n  \
             compressedLayer_{layer_index}.deltasOk deltaTree_{layer_index} = true := by rfl\n\n\
             theorem prefix_ok_{layer_index} :\n  \
             readLayerPrefix parseCursor_{layer_index} = .ok ({}, {}, {}, {}) := by rfl\n\n\
             theorem segcount_ok_{layer_index} :\n  \
             readSegmentCount {} = .ok ({}, {}) := by rfl\n\n\
             /-- Proved with the byte reader and transferred; the packed reader forces one\n\
                 bignum per byte over the whole token stream, which is what made this the last\n\
                 site to abort on SHA-256's largest layer. -/\n\
             theorem tokens_ok_{layer_index}_fast :\n  \
             readCompressedTokensBT {12} segLensTree_{layer_index} segLens_{layer_index} \
             b{13}\n    \
             = .ok ({14}, {15}, {16}, bparseCursor_{17}) := by rfl\n\
             theorem tokens_ok_{layer_index} :\n  \
             readCompressedTokens {12} segLens_{layer_index} {13}\n    \
             = .ok ({14}, {15}, {16}, parseCursor_{17}) :=\n  \
             readCompressedTokens_transferT {12} segLensTree_{layer_index} \
             segLens_{layer_index} href_{13}\n    \
             hrefParse_{17} tokens_ok_{layer_index}_fast\n\n\
             theorem parse_layer_ok_{layer_index} :\n  \
             readCompressedLayer {18} {19} parseCursor_{layer_index} =\n    \
             .ok (compressedLayer_{layer_index}, {20}, parseCursor_{21}) :=\n  \
             readCompressedLayer_eq_of_stages {22} {23} prefix_ok_{layer_index}\n    \
             deltas_all_ok_{layer_index} segcount_ok_{layer_index}\n    \
             segments_all_ok_{layer_index}\n    \
             (seg_lens_ok_{layer_index} \u{25b8} tokens_ok_{layer_index}) (by decide)\n\
             end Quadcert.Gen.{name}\n",
            layer.logw(),
            layer.nw(),
            lean_token_encoding(layer.delta_tokens()),
            layer.delta_tokens().len(),
            layer.num_terms(),
            layer.logw(),
            layer.nw(),
            st.delta_count,
            cur_name("prefix"),
            cur_name(&format!("d{ndchunks}")),
            st.segment_count,
            cur_name("segcount"),
            st.segment_count,
            cur_name(&format!("s{nschunks}")),
            lean_token_encoding(layer.delta_tokens()),
            layer.delta_tokens().len(),
            layer.num_terms(),
            layer_index + 1,
            circuit.raw.constants.len(),
            prior_terms,
            prior_terms + layer.num_terms(),
            layer_index + 1,
            circuit.raw.constants.len(),
            prior_terms,
            seg_lens_tree = {
                let ls: Vec<usize> = segments.iter().map(Vec::len).collect();
                lean_nat_tree(&ls, 0, ls.len())
            },
        );
        write_module(
            output,
            &format!("Gen/{name}/{name}CompressedLayer{layer_index}.lean"),
            &layer_module,
        )?;

        let (terms, checkpoints) = expand_layer(layer)?;
        let nchunks = terms.len().div_ceil(term_chunk_size);
        for chunk_index in 0..nchunks {
            let lo = chunk_index * term_chunk_size;
            let hi = ((chunk_index + 1) * term_chunk_size).min(terms.len());
            let start = &checkpoints[lo];
            let stop = &checkpoints[hi];
            let chunk_module = format!(
                "-- Generated by `lfc2_to_lean`; do not edit.\n\
                 import quadcert.Gen.{name}.{name}CompressedLayer{layer_index}\n\
                 import quadcert.Core.Lfc2Chunk\n\
                 set_option maxRecDepth 1000000\n\
                 set_option maxHeartbeats 0\n\
                 namespace Quadcert.Gen.{name}\n\
                 open Quadcert Quadcert.Lfc2\n\n\
                 def terms_{layer_index}_{chunk_index} : List RawTerm := {}\n\
                 def start_{layer_index}_{chunk_index} : ExpansionCursor := {}\n\
                 def stop_{layer_index}_{chunk_index} : ExpansionCursor := {}\n\
                 theorem expansion_ok_{layer_index}_{chunk_index} :\n\
                   compressedLayer_{layer_index}.expandChunk {g_bound} deltaTree_{layer_index} {} start_{layer_index}_{chunk_index}\n\
                     = .ok (terms_{layer_index}_{chunk_index}, stop_{layer_index}_{chunk_index}) :=\n\
                   -- `by rfl` directly on `_ = .ok (..)` blows the native stack on some chunks\n\
                   -- even though the reduction itself is fine; see `quadcert/Lfc2Chunk.lean`.\n\
                   eq_ok_of_toOption (by rfl)\n\
                 end Quadcert.Gen.{name}\n",
                lean_terms(&terms[lo..hi]),
                lean_checkpoint(layer_index, layer.delta_tokens(), start),
                lean_checkpoint(layer_index, layer.delta_tokens(), stop),
                hi - lo,
            );
            write_module(
                output,
                &format!("Gen/{name}/{name}Expansion{layer_index}_{chunk_index}.lean"),
                &chunk_module,
            )?;
        }

        let expansion_imports = (0..nchunks)
            .map(|chunk| format!("import quadcert.Gen.{name}.{name}Expansion{layer_index}_{chunk}\n"))
            .collect::<String>();
        let term_names = (0..nchunks)
            .map(|chunk| format!("terms_{layer_index}_{chunk}"))
            .collect::<Vec<_>>()
            .join(" ++ ");
        let mut composition = String::new();
        if nchunks == 1 {
            writeln!(
                composition,
                "  simpa [allTerms_{layer_index}, start_{layer_index}_0] using expansion_ok_{layer_index}_0"
            )
            .expect("write String");
        } else {
            writeln!(composition, "  have h_0 := expansion_ok_{layer_index}_0")
                .expect("write String");
            for chunk in 1..nchunks {
                writeln!(
                    composition,
                    "  have h_{chunk} := compressedLayer_{layer_index}.expandChunk_compose {g_bound} deltaTree_{layer_index} h_{} expansion_ok_{layer_index}_{chunk}",
                    chunk - 1,
                )
                .expect("write String");
            }
            writeln!(
                composition,
                "  simpa [allTerms_{layer_index}, start_{layer_index}_0, Nat.reduceAdd, List.append_assoc] using h_{}",
                nchunks - 1,
            )
            .expect("write String");
        }
        let final_stop = format!("stop_{layer_index}_{}", nchunks - 1);
        let expanded_layer_module = format!(
            "-- Generated by `lfc2_to_lean`; do not edit.\n\
             {expansion_imports}\
             set_option maxRecDepth 1000000\n\
             set_option maxHeartbeats 0\n\
             namespace Quadcert.Gen.{name}\n\
             open Quadcert Quadcert.Lfc2\n\n\
             def allTerms_{layer_index} : List RawTerm := {term_names}\n\
             def decodedLayer_{layer_index} : DecodedLayer :=\n\
               {{ logw := {}, nw := {}, terms := allTerms_{layer_index} }}\n\n\
             theorem expansion_all_ok_{layer_index} :\n\
               compressedLayer_{layer_index}.expandChunk {g_bound} deltaTree_{layer_index} {} compressedLayer_{layer_index}.initialCursor\n\
                 = .ok (allTerms_{layer_index}, {final_stop}) := by\n\
             {composition}\n\
             theorem expansion_finished_{layer_index} :\n\
               compressedLayer_{layer_index}.finished {g_bound} deltaTree_{layer_index} {final_stop} = true := by rfl\n\n\
             theorem layer_expand_ok_{layer_index} :\n\
               compressedLayer_{layer_index}.expand {g_bound} deltaTree_{layer_index} = .ok decodedLayer_{layer_index} := by exact compressedLayer_{layer_index}.expand_eq_of_chunk {g_bound} deltaTree_{layer_index} deltas_ok_{layer_index} expansion_all_ok_{layer_index} expansion_finished_{layer_index}\n\
             end Quadcert.Gen.{name}\n",
            layer.logw(),
            layer.nw(),
            layer.num_terms(),
        );
        write_module(
            output,
            &format!("Gen/{name}/{name}ExpandedLayer{layer_index}.lean"),
            &expanded_layer_module,
        )?;
        prior_terms += layer.num_terms();
    }

    let layer_imports = (0..circuit.raw.layers.len())
        .map(|index| format!("import quadcert.Gen.{name}.{name}CompressedLayer{index}\n"))
        .collect::<String>();
    let compressed_layers = (0..circuit.raw.layers.len())
        .map(|index| format!("compressedLayer_{index}"))
        .collect::<Vec<_>>()
        .join(", ");
    let compressed_module = format!(
        "-- Generated by `lfc2_to_lean`; do not edit.\n\
         {layer_imports}\
         namespace Quadcert.Gen.{name}\n\
         open Quadcert.Lfc2\n\n\
         def compressed : CompressedCircuit := {{ fieldId := {}, ninput := {}, npublicInput := {}, noutput := {}, logv := {}, subfieldBoundary := {}, constants := #[{}], layers := [{compressed_layers}], legacyCircuitId := 0x{} }}\n\
         end Quadcert.Gen.{name}\n",
        field_id as u32,
        circuit.raw.ninput,
        circuit.raw.npublic_input,
        circuit.raw.noutput,
        circuit.raw.logv,
        circuit.raw.subfield_boundary,
        constants,
        packed_hex(&circuit.id),
    );
    write_module(
        output,
        &format!("Gen/{name}/{name}Compressed.lean"),
        &compressed_module,
    )?;

    let expanded_imports = (0..circuit.raw.layers.len())
        .map(|index| format!("import quadcert.Gen.{name}.{name}ExpandedLayer{index}\n"))
        .collect::<String>();
    let decoded_layers = (0..circuit.raw.layers.len())
        .map(|index| format!("decodedLayer_{index}"))
        .collect::<Vec<_>>()
        .join(", ");
    let delta_tree_names = (0..circuit.raw.layers.len())
        .map(|index| format!("deltaTree_{index}"))
        .collect::<Vec<_>>()
        .join(", ");
    let compressed_layer_names = (0..circuit.raw.layers.len())
        .map(|index| format!("compressedLayer_{index}"))
        .collect::<Vec<_>>()
        .join(", ");
    let layer_pairs = (0..circuit.raw.layers.len())
        .rev()
        .fold("LayersExpand.nil".to_string(), |rest, index| {
            format!("LayersExpand.cons layer_expand_ok_{index} ({rest})")
        });
    // Bound on `g` for layer 0; each `LayersExpand.cons` re-derives the rest from `nw`.
    let noutput = circuit.raw.noutput;
    // `maxRecDepth` here, rather than `write_module`'s default 1,000,000.  The depth is in the
    // implicit arguments of the `LayersExpand.cons` chain *and* in whnf'ing the `deltaTree_i`
    // literals it unifies against, so it scales with both the layer count and the largest delta
    // table.  ECDSA2 (11 layers, 11,952 deltas) fits in 1,000,000; mdoc's signature circuit
    // (21 layers, 9,856) does not, and fails 1,032 modules into a 1,037-module build.  4,000,000
    // covers it at ~4.3 GB resident; the hash circuit's 39,690-delta layer wants more headroom
    // still, which is why this is scaled rather than a second magic constant.
    let decoded_rec_depth = 4_000_000
        + 400 * circuit.raw.layers.iter().map(|l| l.deltas().len()).max().unwrap_or(0);
    let decoded_module = format!(
        "-- Generated by `lfc2_to_lean`; do not edit.\n\
         import quadcert.Gen.{name}.{name}Compressed\n\
         {expanded_imports}\
         set_option maxRecDepth {decoded_rec_depth}\nset_option maxHeartbeats 0\n\
         namespace Quadcert.Gen.{name}\n\
         open Quadcert.Lfc2\n\n\
         def decoded : DecodedCircuit := {{ fieldId := compressed.fieldId, ninput := compressed.ninput, npublicInput := compressed.npublicInput, noutput := compressed.noutput, logv := compressed.logv, subfieldBoundary := compressed.subfieldBoundary, constants := compressed.constants, layers := [{decoded_layers}], legacyCircuitId := compressed.legacyCircuitId }}\n\n\
         def deltaTrees : List (PTree Delta) := [{delta_tree_names}]\n\n\
         theorem expanded_layers_ok : expandLayers compressed.noutput deltaTrees compressed.layers [] = .ok [{decoded_layers}] := by change expandLayers {noutput} [{delta_tree_names}] [{compressed_layer_names}] [] = .ok [{decoded_layers}]; exact expandLayers_eq_of_pairs ({layer_pairs}) []\n\n\
         theorem compressed_expand_ok : compressed.expand deltaTrees = .ok decoded := by exact compressed.expand_eq_of_layers deltaTrees expanded_layers_ok\n\
         end Quadcert.Gen.{name}\n",
    );
    write_module(output, &format!("Gen/{name}/{name}Decoded.lean"), &decoded_module)?;

    let mut parse_step_tactics = String::new();
    for index in 0..circuit.raw.layers.len() {
        writeln!(
            parse_step_tactics,
            "  refine LayerParseSteps.cons parse_layer_ok_{index} ?_"
        )
        .expect("write String");
    }
    parse_step_tactics.push_str("  exact LayerParseSteps.nil\n");
    let parse_steps_module = format!(
        "-- Generated by `lfc2_to_lean`; do not edit.\n\
         import quadcert.Gen.{name}.{name}Compressed\n\
         set_option maxRecDepth 1000000\n\
         set_option maxHeartbeats 0\n\
         namespace Quadcert.Gen.{name}\n\
         open Quadcert.Lfc2\n\n\
         theorem parse_steps : LayerParseSteps {} {} 0 [{compressed_layers}] parseCursor_0 parseCursor_{} := by\n\
         {parse_step_tactics}\n\
         end Quadcert.Gen.{name}\n",
        circuit.raw.constants.len(),
        circuit.raw.layers.len(),
        circuit.raw.layers.len(),
    );
    write_module(
        output,
        &format!("Gen/{name}/{name}ParseSteps.lean"),
        &parse_steps_module,
    )?;

    let parse_finish_module = format!(
        "-- Generated by `lfc2_to_lean`; do not edit.\n\
         import quadcert.Gen.{name}.{name}Header\n\
         import quadcert.Gen.{name}.{name}Compressed\n\
         namespace Quadcert.Gen.{name}\n\
         open Quadcert.Lfc2\n\n\
         theorem parse_finish_ok : header.finish [{compressed_layers}] parseCursor_{} = .ok compressed := by rfl\n\
         end Quadcert.Gen.{name}\n",
        circuit.raw.layers.len(),
    );
    write_module(
        output,
        &format!("Gen/{name}/{name}ParseFinish.lean"),
        &parse_finish_module,
    )?;

    let parse_final_module = format!(
        "-- Generated by `lfc2_to_lean`; do not edit.\n\
         import quadcert.Gen.{name}.{name}ParseSteps\n\
         import quadcert.Gen.{name}.{name}ParseFinish\n\
         set_option maxRecDepth 1000000\n\
         namespace Quadcert.Gen.{name}\n\
         open Quadcert.Lfc2\n\n\
         theorem decodeCompressed_ok : decodeCompressed {field_name} packedInput = .ok compressed := by exact decodeCompressed_eq_of_stages {field_name} packedInput parse_header_ok parse_steps parse_finish_ok\n\
         end Quadcert.Gen.{name}\n"
    );
    write_module(
        output,
        &format!("Gen/{name}/{name}ParseFinal.lean"),
        &parse_final_module,
    )?;

    let decode_module = format!(
        "-- Generated by `lfc2_to_lean`; do not edit.\n\
         import quadcert.Gen.{name}.{name}ParseFinal\n\
         import quadcert.Gen.{name}.{name}Decoded\n\
         set_option maxRecDepth 1000000\n\
         namespace Quadcert.Gen.{name}\n\
         open Quadcert.Lfc2\n\n\
         theorem decode_ok : decode {field_name} packedInput deltaTrees = .ok decoded := by exact decode_eq_of_compressed {field_name} packedInput deltaTrees decodeCompressed_ok compressed_expand_ok\n\
         end Quadcert.Gen.{name}\n"
    );
    write_module(output, &format!("Gen/{name}/{name}Decode.lean"), &decode_module)?;

    Ok(())
}

fn expand_layer<F: SerializableField>(
    layer: &Layer<F>,
) -> Result<(Vec<ExpandedTerm>, Vec<ExpansionCheckpoint>), String> {
    // Mirrors `nextTermLoop` exactly: pop from the open segment, else open the next one from the
    // token stream.  Only `outer` is tracked as a count, because the Lean cursor recovers it as
    // `initialCursor.outer.drop n`; `segment` is small enough to write out literally.
    let roots: &[u32] = layer.delta_tokens();
    let mut terms = Vec::with_capacity(layer.num_terms());
    let mut checkpoints = Vec::with_capacity(layer.num_terms() + 1);
    let mut cursor = ExpansionCheckpoint::default();
    checkpoints.push(cursor.clone());

    while terms.len() < layer.num_terms() {
        if cursor.segment.is_empty() {
            if cursor.outer_drop < roots.len() {
                let token = roots[cursor.outer_drop] as usize;
                cursor.outer_drop += 1;
                cursor.segment = layer
                    .delta_segments()
                    .get(token)
                    .ok_or_else(|| "segment index out of bounds".to_string())?
                    .clone();
            } else {
                return Err("token grammar ended before advertised term count".to_string());
            }
            continue;
        }
        let delta_index = cursor.segment.remove(0) as usize;
        let delta = layer
            .deltas()
            .get(delta_index)
            .ok_or_else(|| "delta index out of bounds".to_string())?;
        cursor.delta_pos = delta_index;
        cursor.g = cursor.g.wrapping_add(delta.g);
        cursor.h0 = cursor.h0.wrapping_add(delta.h[0]);
        cursor.h1 = cursor.h1.wrapping_add(delta.h[1]);
        cursor.emitted += 1;
        terms.push(ExpandedTerm {
            g: cursor.g,
            h0: cursor.h0,
            h1: cursor.h1,
            k_index: delta.k_index,
        });
        checkpoints.push(cursor.clone());
    }
    Ok((terms, checkpoints))
}

/// A balanced positional tree over the delta table, emitted as advice.  Indexing an `Array` in
/// the Lean kernel walks `i` cons cells; a tree answers in `log n` steps.  The tree is tied back
/// to the parsed list by `deltasOk`, so wrong advice cannot pass.
/// Balanced positional trees for the token stage's two lookup tables. Same shape as
/// `lean_delta_tree`: untrusted advice, validated in Lean by `treeOk` in one linear pass, and
/// answering `lengths[i]?` / `phrases[i]?` in `log n` instead of `i` steps. Without these,
/// counting SHA-256 layer 5's terms is ~1.6e8 list steps inside one `rfl`.
fn lean_nat_tree(ns: &[usize], lo: usize, hi: usize) -> String {
    if lo >= hi {
        return "PTree.leaf".to_string();
    }
    let mid = (lo + hi) / 2;
    format!(
        "(PTree.node {} {} {} {})",
        mid - lo,
        lean_nat_tree(ns, lo, mid),
        ns[mid],
        lean_nat_tree(ns, mid + 1, hi)
    )
}

fn lean_arr_tree(xs: &[Vec<u32>], lo: usize, hi: usize) -> String {
    if lo >= hi {
        return "PTree.leaf".to_string();
    }
    let mid = (lo + hi) / 2;
    let items = xs[mid].iter().map(u32::to_string).collect::<Vec<_>>().join(", ");
    format!(
        "(PTree.node {} {} (Array.mk [{}]) {})",
        mid - lo,
        lean_arr_tree(xs, lo, mid),
        items,
        lean_arr_tree(xs, mid + 1, hi)
    )
}

fn lean_delta_tree(ds: &[(u32, u32, u32, u32)], lo: usize, hi: usize) -> String {
    if lo >= hi {
        return "PTree.leaf".to_string();
    }
    let mid = (lo + hi) / 2;
    let d = ds[mid];
    format!(
        "(PTree.node {} {} \u{27e8}{}, {}, {}, {}\u{27e9} {})",
        mid - lo,
        lean_delta_tree(ds, lo, mid),
        d.0,
        d.1,
        d.2,
        d.3,
        lean_delta_tree(ds, mid + 1, hi)
    )
}

