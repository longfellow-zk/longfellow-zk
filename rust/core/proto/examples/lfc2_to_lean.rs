fn lean_checkpoint(layer_index: usize, roots: &[u32], cursor: &ExpansionCheckpoint) -> String {
    // The very first checkpoint must be *syntactically* `initialCursor`, since that is the form
    // `expand_eq_of_chunk` expects; an equal-but-expanded record does not unify.
    if cursor.outer_drop == 0
        && cursor.segment.is_empty()
        && cursor.emitted == 0
        && cursor.delta_pos == 0
    {
        return format!("compressedLayer_{layer_index}.initialCursor");
    }
    let list = |v: &[u32]| {
        v.iter()
            .map(u32::to_string)
            .collect::<Vec<_>>()
            .join(", ")
    };
    // `outer` is written out **literally**, not as `initialCursor.outer.drop n`.
    //
    // A `.drop n` checkpoint is not reduced when the module is elaborated, so every one of the
    // chunk's emission steps re-reduces the whole drop chain from scratch -- the kernel has no
    // sharing -- and the nesting depth grows with the step count.  The last chunk of ECDSA2's
    // layer 10 blew `maxRecDepth` at 1,000,000 that way while its earlier siblings passed.
    //
    // The residual list costs `roots.len() - outer_drop` numerals per checkpoint, which summed
    // over a layer's chunks is about `nchunks * ntokens / 2` -- a few thousand `Nat` literals
    // for ECDSA2, against a reduction that does not finish.
    format!(
        "{{ outer := [{}], \
         segment := [{}], g := {}, h0 := {}, h1 := {}, emitted := {} }}",
        list(&roots[cursor.outer_drop.min(roots.len())..]),
        list(&cursor.segment),
        cursor.g,
        cursor.h0,
        cursor.h1,
        cursor.emitted,
    )
}

fn lean_field_name(field_id: FieldID) -> Result<&'static str, String> {
    match field_id {
        FieldID::P256 => Ok("p256"),
        FieldID::Gf2_128 => Ok("gf2_128"),
        _ => Err(format!("no Lean FieldEncoding for {field_id:?}")),
    }
}

fn read_uleb_offset(bytes: &[u8], offset: &mut usize) -> Result<usize, String> {
    let mut value = 0usize;
    let mut place = 1usize;
    for _ in 0..4 {
        let byte = *bytes
            .get(*offset)
            .ok_or_else(|| "truncated LFC2 while locating layers".to_string())?;
        *offset += 1;
        value = value
            .checked_add(usize::from(byte & 0x7f).saturating_mul(place))
            .ok_or_else(|| "ULEB overflow while locating layers".to_string())?;
        if byte < 0x80 {
            return Ok(value);
        }
        place = place
            .checked_mul(128)
            .ok_or_else(|| "ULEB overflow while locating layers".to_string())?;
    }
    Err("overlong ULEB while locating layers".to_string())
}

fn skip_ulebs(bytes: &[u8], offset: &mut usize, count: usize) -> Result<(), String> {
    for _ in 0..count {
        read_uleb_offset(bytes, offset)?;
    }
    Ok(())
}

/// Byte offsets of every stage boundary inside one layer, so the parser can be certified in
/// bounded pieces.  Mirrors `readCompressedLayer`'s reading order exactly.
struct LayerStages {
    after_prefix: usize,
    delta_count: usize,
    /// `delta_bounds[j]` is the offset before delta chunk `j`; last entry is the end.
    delta_bounds: Vec<usize>,
    after_seg_count: usize,
    segment_count: usize,
    segment_bounds: Vec<usize>,
    after_tokens: usize,
}

fn lfc2_layer_stages(
    bytes: &[u8],
    start: usize,
    chunk: usize,
) -> Result<LayerStages, String> {
    let mut offset = start;
    skip_ulebs(bytes, &mut offset, 2)?; // logw, nw
    let delta_count = read_uleb_offset(bytes, &mut offset)?;
    let after_prefix = offset;

    let mut delta_bounds = vec![offset];
    let mut done = 0usize;
    while done < delta_count {
        let take = chunk.min(delta_count - done);
        skip_ulebs(bytes, &mut offset, take * 4)?; // g, h0, h1, kIndex
        delta_bounds.push(offset);
        done += take;
    }

    let segment_count = read_uleb_offset(bytes, &mut offset)?;
    let after_seg_count = offset;

    let mut segment_bounds = vec![offset];
    let mut done = 0usize;
    while done < segment_count {
        let take = chunk.min(segment_count - done);
        for _ in 0..take {
            let length = read_uleb_offset(bytes, &mut offset)?;
            skip_ulebs(bytes, &mut offset, length)?;
        }
        segment_bounds.push(offset);
        done += take;
    }

    let count = read_uleb_offset(bytes, &mut offset)?;
    skip_ulebs(bytes, &mut offset, count)?;

    Ok(LayerStages {
        after_prefix,
        delta_count,
        delta_bounds,
        after_seg_count,
        segment_count,
        segment_bounds,
        after_tokens: offset,
    })
}

fn lfc2_layer_offsets(bytes: &[u8], field_bytes: usize) -> Result<Vec<usize>, String> {
    if !bytes.starts_with(b"LFC2") {
        return Err("generated payload is not LFC2".to_string());
    }
    let mut offset = 4usize;
    let mut header = [0usize; 7];
    for value in &mut header {
        *value = read_uleb_offset(bytes, &mut offset)?;
    }
    let layer_count = header[6];
    let constant_count = read_uleb_offset(bytes, &mut offset)?;
    offset = offset
        .checked_add(constant_count.saturating_mul(field_bytes))
        .ok_or_else(|| "constant table size overflow".to_string())?;
    if offset > bytes.len() {
        return Err("truncated LFC2 constant table".to_string());
    }

    let mut offsets = Vec::with_capacity(layer_count + 1);
    for _ in 0..layer_count {
        offsets.push(offset);
        skip_ulebs(bytes, &mut offset, 2)?; // logw, nw
        let delta_count = read_uleb_offset(bytes, &mut offset)?;
        skip_ulebs(bytes, &mut offset, delta_count.saturating_mul(4))?;
        let segment_count = read_uleb_offset(bytes, &mut offset)?;
        for _ in 0..segment_count {
            let length = read_uleb_offset(bytes, &mut offset)?;
            skip_ulebs(bytes, &mut offset, length)?;
        }
        let count = read_uleb_offset(bytes, &mut offset)?;
        skip_ulebs(bytes, &mut offset, count)?;
    }
    offsets.push(offset);
    if offset.checked_add(32) != Some(bytes.len()) {
        return Err("located LFC2 layers do not end at the 32-byte trailer".to_string());
    }
    Ok(offsets)
}

fn lean_parse_cursor(bytes: &[u8], offset: usize) -> String {
    assert!(
        offset < bytes.len(),
        "parse cursor must precede the trailer"
    );
    // A position, not a copy.  Writing the cursor out literally would embed the current page's
    // remaining bytes and every later page -- 3.9 MB for one SHA-256 layer's checkpoints.
    format!("cursorAt packedInput {offset}")
}

/// Writes a generated module, guaranteeing it carries the recursion/heartbeat options.
///
/// These are not a tuning knob to sprinkle where a module happens to need them. Lean's default
/// `maxRecDepth` is 512, and unification against a generated literal exceeds that at sizes that
/// are impossible to predict from the module's source: ECDSA2's `Decoded` module is 20 lines and
/// still overflowed, because the depth is in the *implicit arguments* of an 11-deep
/// `LayersExpand.cons` chain, not in anything visible. Injecting them centrally means a new
/// module kind cannot be added without them.
fn write_module(output: &Path, name: &str, contents: &str) -> Result<(), String> {
    const OPTIONS: &str = "set_option maxRecDepth 1000000\nset_option maxHeartbeats 0\n";
    let contents = if contents.contains("set_option maxRecDepth") {
        contents.to_string()
    } else {
        // After the import block, which must come first in a Lean module.
        let split = contents
            .match_indices('\n')
            .filter(|(i, _)| {
                contents[..*i]
                    .rsplit('\n')
                    .next()
                    .is_some_and(|line| line.starts_with("import "))
            })
            .map(|(i, _)| i + 1)
            .next_back()
            .unwrap_or(0);
        format!("{}{OPTIONS}{}", &contents[..split], &contents[split..])
    };
    let path = output.join(name);
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent).map_err(|error| format!("create dir for {name}: {error}"))?;
    }
    fs::write(path, &contents).map_err(|error| format!("write {name}: {error}"))
}

fn packed_hex(bytes: &[u8]) -> String {
    let mut result = String::with_capacity(bytes.len() * 2);
    for byte in bytes.iter().rev() {
        write!(result, "{byte:02x}").expect("write String");
    }
    let trimmed = result.trim_start_matches('0');
    if trimmed.is_empty() {
        "0".to_string()
    } else {
        trimmed.to_string()
    }
}

fn lean_bytes(bytes: &[u8]) -> String {
    format!(
        "[{}]",
        bytes
            .iter()
            .map(|byte| format!("0x{byte:02x}"))
            .collect::<Vec<_>>()
            .join(", ")
    )
}

fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|byte| format!("{byte:02x}")).collect()
}
