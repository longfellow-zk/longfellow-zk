//! Deterministic offline publication of candidate v2 parameter records.
use crate::Result;

#[cfg(all(feature = "compiler", feature = "mdoc"))]
pub(crate) fn run() -> Result<()> {
    use std::fmt::Write;

    use longfellow_zk::mdoc::{development_provider, v2};

    crate::profiles::audit(crate::profiles::Protocol::Polygero)?;
    // Collect a complete candidate set before printing; publication remains explicit.
    let mut records =
        String::from("// Generated by zk_tool generate-v2-specs; review before publication.\n");
    for count in 1..=4 {
        let provided = development_provider::compile_next(count)?;
        let spec = *provided.spec();
        if let Some(registered) = v2::find_zk_spec(v2::SYSTEM_ID, &spec.combined_hash) {
            crate::require(
                *registered == spec,
                "registered specification changed; do not silently retune it",
            )?;
        }
        writeln!(&mut records, "{spec:?},")?;
    }
    print!("{records}");
    Ok(())
}
#[cfg(not(all(feature = "compiler", feature = "mdoc")))]
pub fn run() -> Result<()> {
    Err("generate-v2-specs requires compiler and mdoc features".into())
}
