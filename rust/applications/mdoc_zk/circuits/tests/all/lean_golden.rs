//! Emits a real `mdoc_hash` input as a Lean `MDoc.Witness`/`MDoc.Statement`, so that
//! `formal/circuits/mdoc/GoldenCheck.lean` can `decide` every clause of the specification
//! against it. The specification is written by hand from this crate's source; this test is what
//! catches a transcription that drifted.
//!
//! Writes nothing unless `MDOC_LEAN_GOLDEN_OUT` is set:
//!
//! ```text
//! MDOC_LEAN_GOLDEN_OUT=formal/circuits/mdoc/Golden.lean \
//!   cargo test -p mdoc_zk_circuits --test circuits_tests lean_golden
//! ```

#![allow(dead_code)]

use compile_algebra::CompileNat;
use core_algebra::Nat;
use mdoc_zk_circuits::{
    hash::{concrete::ConcreteGiven, given, hash_input_of_parsed_mdoc, HashMac},
    parse_test_data,
};

/// Arbitrary but fixed, so the emitted vector is reproducible. Non-zero on purpose: with
/// `mac_av = 0` the MAC clause degenerates to `tag = pad` and checks nothing about the
/// GF(2^128) multiply.
const MAC_AV: u128 = 0x0f1e_2d3c_4b5a_6978_8796_a5b4_c3d2_e1f0;
const MAC_AP: [[u128; 2]; 3] = [
    [0x1111_2222_3333_4444_5555_6666_7777_8888, 0x9999_aaaa_bbbb_cccc_dddd_eeee_ffff_0000],
    [0x0123_4567_89ab_cdef_fedc_ba98_7654_3210, 0x2468_ace0_1357_9bdf_0f0f_f0f0_00ff_ff00],
    [0xdead_beef_dead_beef_cafe_babe_cafe_babe, 0x0000_0001_0000_0002_0000_0003_0000_0004],
];

fn list(bytes: &[u8]) -> String {
    let mut s = String::from("[");
    for (i, b) in bytes.iter().enumerate() {
        if i > 0 {
            s.push(',');
        }
        s.push_str(&b.to_string());
    }
    s.push(']');
    s
}

fn nat_list(xs: &[usize]) -> String {
    let mut s = String::from("[");
    for (i, x) in xs.iter().enumerate() {
        if i > 0 {
            s.push(',');
        }
        s.push_str(&x.to_string());
    }
    s.push(']');
    s
}

/// The 256-bit value as 32 **big-endian** bytes. `Spec.lean` reads `e`, `dpkX` and `dpkY` in the
/// order they appear in the MSO, which is big-endian; the Rust MAC path uses the little-endian
/// limb order, so this is where the two conventions meet.
fn be32<N: Nat<4>>(n: &N) -> Vec<u8> {
    let mut bytes = n.to_bytes_le();
    assert!(bytes.len() <= 32);
    bytes.resize(32, 0);
    bytes.reverse();
    bytes
}

fn emit(g: &ConcreteGiven<CompileNat<4>>) -> String {
    let mut out = String::new();
    out.push_str(
        "/-\n\
         # A real credential, as spec data\n\n\
         Generated by `rust/applications/mdoc_zk/circuits/tests/all/lean_golden.rs` from\n\
         `mdoc_zk_testcases::vectors::TEST_DATA`, the same vector\n\
         `hash_eval.rs::test_eval_mdoc_hash_independent` runs the circuit on. Data only; the\n\
         checks are in `GoldenCheck.lean`.\n\n\
         Do not edit by hand -- regenerate with\n\n\
         ```\n\
         MDOC_LEAN_GOLDEN_OUT=formal/circuits/mdoc/Golden.lean \\\n\
         \x20 cargo test -p mdoc_zk_circuits --test circuits_tests lean_golden\n\
         ```\n\
         -/\n\n\
         import mdoc.Spec\n\n\
         namespace MDoc\n\
         namespace Golden\n\n",
    );

    // Split at the active-block boundary. Everything past `nblocks * 64` is zero by
    // `assert_sha_padding`, and emitting it as `List.replicate` rather than 2112 literal zeros is
    // what makes the padding clause checkable in seconds instead of minutes: Lean proves the tail
    // is zero by one lemma instead of one list traversal per index.
    let active_len = g.nblocks as usize * 64;
    assert!(active_len <= g.preimage.value.len());
    assert!(
        g.preimage.value[active_len..].iter().all(|&b| b == 0),
        "bytes past the active blocks must be zero"
    );
    out.push_str(&format!("def active : List Nat := {}\n\n", list(&g.preimage.value[..active_len])));
    out.push_str(&format!(
        "/-- The full {}-byte buffer: {} active bytes, then zeros. -/\n\
         def preimage : List Nat := active ++ List.replicate {} 0\n\n",
        g.preimage.value.len(),
        active_len,
        g.preimage.value.len() - active_len
    ));

    for (i, a) in g.attribute_given.iter().enumerate() {
        out.push_str(&format!("def attrPre{} : List Nat := {}\n", i, list(&a.padded_preimage)));
    }
    out.push('\n');

    out.push_str("def attrs : List AttrWitness := [\n");
    for (i, a) in g.attribute_given.iter().enumerate() {
        let p = a.field_locator.permutation;
        let perm: Vec<usize> = (0..4).map(|k| (p >> (2 * k)) & 3).collect();
        out.push_str(&format!(
            "  {{ preimage := attrPre{}, len := {}, digestOff := {},\n    \
             slotPos := {}, slotLen := {}, perm := {} }}{}\n",
            i,
            a.unpadded_preimage_len,
            a.mso_digest_offset_in_preimage,
            nat_list(&a.field_locator.slot_position),
            nat_list(&a.field_locator.length),
            nat_list(&perm),
            if i + 1 == g.attribute_given.len() { "" } else { "," }
        ));
    }
    out.push_str("]\n\n");

    out.push_str(&format!(
        "def w : Witness :=\n  \
         {{ preimage := preimage, msgLen := {}, nblocks := {}\n    \
         e := {}\n    \
         dpkX := {}\n    \
         dpkY := {}\n    \
         docTypeOff := {}, validFromOff := {}, validUntilOff := {}\n    \
         devKeyInfoOff := {}, valueDigestsOff := {}\n    \
         attrs := attrs\n    \
         macPad := [({}, {}), ({}, {}), ({}, {})] }}\n\n",
        g.preimage.len,
        g.nblocks,
        list(&be32(&g.hash_input.issuer_sig_e)),
        list(&be32(&g.hash_input.device_pk.0)),
        list(&be32(&g.hash_input.device_pk.1)),
        g.doc_type_offset_in_preimage,
        g.valid_from_offset_in_preimage,
        g.valid_until_offset_in_preimage,
        g.dev_key_info_offset_in_preimage,
        g.value_digests_offset_in_preimage,
        g.mac_ap[0][0], g.mac_ap[0][1],
        g.mac_ap[1][0], g.mac_ap[1][1],
        g.mac_ap[2][0], g.mac_ap[2][1],
    ));

    let ids: Vec<String> = g.attribute_given.iter().map(|a| list(&a.expected_name)).collect();
    let vals: Vec<String> =
        g.attribute_given.iter().map(|a| list(&a.expected_cbor_value)).collect();

    out.push_str(&format!(
        "def st : Statement :=\n  \
         {{ now := {}\n    \
         attrId := [{}]\n    \
         attrValue := [{}]\n    \
         suppressDocType := {}\n    \
         docType := {}\n    \
         macKey := {}\n    \
         macE := ({}, {}), macDpkX := ({}, {}), macDpkY := ({}, {}) }}\n\n",
        list(&g.hash_input.now),
        ids.join(", "),
        vals.join(", "),
        g.hash_input.suppress_doc_type_check,
        list(&g.hash_input.expected_doc_type),
        g.mac_input.mac_av,
        g.mac_e[0], g.mac_e[1],
        g.mac_device_pkx[0], g.mac_device_pkx[1],
        g.mac_device_pky[0], g.mac_device_pky[1],
    ));

    out.push_str("end Golden\nend MDoc\n");
    out
}

#[test]
fn lean_golden_vector() {
    let (_, parsed, now) =
        parse_test_data::<4, CompileNat<4>>(&mdoc_zk_testcases::vectors::TEST_DATA);
    let hash_input = hash_input_of_parsed_mdoc(&parsed, &parsed.all_attr_ids(), now);
    let mac_input = HashMac { mac_av: MAC_AV, mac_ap: MAC_AP };
    let g = given::<4, _>(hash_input, mac_input);

    // Sanity: the vector we are about to emit is the one the circuit accepts.
    assert!(g.nblocks as usize >= 1);
    assert_eq!(g.preimage.value.len(), 40 * 64);
    assert!(!g.attribute_given.is_empty());

    let text = emit(&g);
    match std::env::var("MDOC_LEAN_GOLDEN_OUT") {
        Ok(path) => {
            std::fs::write(&path, text).expect("write Lean golden vector");
            eprintln!("wrote {path}");
        }
        Err(_) => {
            // Still exercise the emitter, so a change that breaks it fails in CI.
            assert!(text.contains("def w : Witness"));
            assert!(text.contains("def st : Statement"));
        }
    }
}
